# 2048×2048 benchmark textures for `cargo run --release -p specular-texture --example
# bench-texture`. Sourced by tools/corpus/fetch-textures.sh (OUT, ORACLES, check_space,
# provenance); not run by default: `tools/corpus/fetch-textures.sh bench_textures`, after
# oracle_basis and oracle_astc have built the encoders.
#
# Writes $OUT/bench/:
#   uastc_2048.ktx2, etc1s_2048.ktx2   basisu, kodim03 resampled to 2048², UASTC level 1 / ETC1S
#   uastc_2048_*.ktx                   basisu -unpack of the UASTC file: ETC2 RGBA, ASTC 4×4,
#                                      PVRTC1 4 bpp (KTX1), plus the RGBA PNG
#   astc8x8_2048.astc                  astcenc -cl 8x8 -medium of that PNG

bench_textures() {
  local basisu="$ORACLES/basis_universal/bin/basisu" astcenc="$ORACLES/astcenc/bin/astcenc-none"
  local dir="$OUT/bench" img="$ORACLES/basis_universal/test_files/kodim03.png"
  [[ -x $basisu ]] || die "no basisu: run oracle_basis first"
  check_space
  mkdir -p "$dir"
  if [[ ! -f $dir/uastc_2048.ktx2 ]]; then
    (cd "$dir" && nice "$basisu" -ktx2 -uastc -uastc_level 1 -resample 2048 2048 -file "$img" \
      -output_file "$dir/uastc_2048.ktx2" >/dev/null)
  fi
  if [[ ! -f $dir/etc1s_2048.ktx2 ]]; then
    (cd "$dir" && nice "$basisu" -ktx2 -q 128 -resample 2048 2048 -file "$img" \
      -output_file "$dir/etc1s_2048.ktx2" >/dev/null)
  fi
  if ! compgen -G "$dir/uastc_2048_transcoded_ETC2_RGBA*.ktx" >/dev/null; then
    (cd "$dir" && nice "$basisu" -unpack "$dir/uastc_2048.ktx2" >/dev/null) || true
  fi
  # Keep the formats the bench reads; the unpack writes one file per transcoder target.
  find "$dir" -name 'uastc_2048_*' ! -name '*transcoded_ETC2_RGBA_*.ktx' \
    ! -name '*transcoded_ASTC_LDR_4X4_RGBA_*.ktx' ! -name '*transcoded_PVRTC1_4_RGBA_*.ktx' \
    ! -name '*unpacked_rgba_RGBA32_*.png' -delete
  local png
  png=$(find "$dir" -name '*unpacked_rgba_RGBA32_*.png' | head -1)
  if [[ -x $astcenc && -n $png && ! -f $dir/astc8x8_2048.astc ]]; then
    nice "$astcenc" -cl "$png" "$dir/astc8x8_2048.astc" 8x8 -medium >/dev/null
  fi
  ls -la "$dir"
  for f in "$dir"/*; do provenance "bench/$(basename "$f")" \
    "generated by basisu / astcenc from basis_universal test_files/kodim03.png" \
    'Apache-2.0 (basis_universal); test images'; done
}
