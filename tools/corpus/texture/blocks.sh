# Sourced by tools/corpus/fetch-textures.sh: ETC1 / ETC2 / EAC and PVRTC1 references.
#
# Oracles (built into $ORACLES/blocks): Ericsson's ETCPACK reference decoder (etcdec.cxx) and
# the PowerVR SDK's PVRTDecompress.cpp, each compiled into a small driver of ours
# (etc_ref.cpp, pvrtc_ref.cpp).
#
# Layout under $OUT/blocks/:
#   random/<mode>.<w>x<h>.in    pseudo-random blocks (every ETC2 mode and PVRTC flag shows up)
#   random/<mode>.<w>x<h>.ref   their reference decode
#   files/<name>.<mode>.<w>x<h>.in / .ref   level 0, image 0 of the KTX / KTX2 test files
# <mode> is rgb | rgba1 | rgba8 | r11 | r11s | rg11 | rg11s (etc_ref) or pvrtc2 | pvrtc4.
# .ref is RGBA8, or for the r11 / rg11 modes the 11-bit values as little-endian int16.

ETCPACK_COMMIT=14a64d9d19318fb9f81ce339b7103ffa0f1781d7
PVR_SDK_COMMIT=63f0098acdc11ec9a072c30000d2fa670a955bee

oracle_blocks() {
  local src="$ORACLES/blocks" py="$ROOT/tools/corpus/texture/blocks.py"
  local dst="$OUT/blocks"
  mkdir -p "$src" "$dst/random" "$dst/files"
  curl -fsSL --retry 3 -o "$src/etcdec.cxx" \
    "https://raw.githubusercontent.com/Ericsson/ETCPACK/$ETCPACK_COMMIT/source/etcdec.cxx"
  local sdk="https://raw.githubusercontent.com/powervr-graphics/Native_SDK/$PVR_SDK_COMMIT"
  curl -fsSL --retry 3 -o "$src/PVRTDecompress.cpp" \
    "$sdk/framework/PVRCore/texture/PVRTDecompress.cpp"
  curl -fsSL --retry 3 -o "$src/PVRTDecompress.h" \
    "$sdk/framework/PVRCore/texture/PVRTDecompress.h"
  nice g++ -O2 -w -I"$src" -o "$src/etc_ref" "$ROOT/tools/corpus/texture/etc_ref.cpp"
  nice g++ -O2 -w -I"$src" -o "$src/pvrtc_ref" "$ROOT/tools/corpus/texture/pvrtc_ref.cpp"

  local mode seed=1 bytes
  for mode in rgb rgba1 rgba8 r11 r11s rg11 rg11s; do
    case $mode in rgba8|rg11|rg11s) bytes=16 ;; *) bytes=8 ;; esac
    local base="$dst/random/$mode.512x512"
    python3 -I "$py" random "$base.in" $((128 * 128 * bytes)) $seed
    "$src/etc_ref" "$mode" 512 512 "$base.in" "$base.ref"
    seed=$((seed + 1))
  done
  local spec bpp w h bw
  for spec in "4 256 256" "4 64 32" "4 8 8" "4 4 4" "4 32 128" "4 12 20" \
              "2 256 256" "2 128 32" "2 16 8" "2 8 8" "2 64 256" "2 24 12"; do
    read -r bpp w h <<< "$spec"
    bw=$(( bpp == 2 ? 8 : 4 ))
    local nx=$(( (w + bw - 1) / bw )) ny=$(( (h + 3) / 4 ))
    (( nx < 2 )) && nx=2
    (( ny < 2 )) && ny=2
    local base="$dst/random/pvrtc$bpp.${w}x$h"
    python3 -I "$py" random "$base.in" $((nx * ny * 8)) $seed
    seed=$((seed + 1))
    # The reference needs power-of-two sizes; odd sizes are tested through a larger level.
    if (( (w & (w - 1)) == 0 && (h & (h - 1)) == 0 )); then
      "$src/pvrtc_ref" "$bpp" "$w" "$h" "$base.in" "$base.ref"
    else
      rm -f "$base.in"
    fi
  done

  local f info name n=0
  for f in "$OUT"/ktx-software/tests/resources/ktx/*.ktx \
           "$OUT"/ktx-software/tests/resources/ktx2/*.ktx2; do
    [[ -f $f ]] || continue
    info=$(python3 -I "$py" level0 "$f" "$dst/files/tmp.in")
    [[ $info == skip ]] && continue
    read -r mode w h <<< "$info"
    name=$(basename "$f")
    local base="$dst/files/$name.$mode.${w}x$h"
    mv "$dst/files/tmp.in" "$base.in"
    case $mode in
      pvrtc*) "$src/pvrtc_ref" "${mode#pvrtc}" "$w" "$h" "$base.in" "$base.ref" ;;
      *) "$src/etc_ref" "$mode" "$w" "$h" "$base.in" "$base.ref" ;;
    esac
    n=$((n + 1))
  done
  rm -f "$dst/files/tmp.in"
  provenance "blocks/" "ETCPACK $ETCPACK_COMMIT; PowerVR Native_SDK $PVR_SDK_COMMIT" \
    'references generated by those decoders'
  echo "  blocks: $(ls "$dst/random" | wc -l) random files, $n file references"
}
