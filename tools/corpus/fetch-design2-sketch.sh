#!/usr/bin/env bash
# Fetch the Sketch / Figma test corpus into tools/corpus/design2/sketch/ and design2/figma/
# (gitignored: nothing downloaded here is committed). The specular-sketch corpus test reads
# it from SPECULAR_SKETCH_CORPUS (the design2 directory), else tools/corpus/design2, and
# skips when it is absent.
#
# Usage: tools/corpus/fetch-design2-sketch.sh
#
# What it covers (about 30 MB):
# - IBM Carbon design kits (Apache-2.0): real production documents with symbols, overrides,
#   text styles, images and previews (Sketch 52 to 70 formats).
# - PC108 Simple Sketch Wireframe Kit (no licence stated; dev corpus only).
# - dany2or/UI Clock.sketch: a pre-43 (SQLite) Sketch file, for the refusal.
# - sketch-hq/sketch-reference-files (MIT): the JSON of small feature documents written by
#   Sketch itself (shapes, shape paths, groups, symbols, overrides, text, images, blur...),
#   zipped here into .sketch files (they have no preview).
# - Figma: no freely licensed local copies are published; tools/corpus/design2-sketch-oracle.py
#   is not used for them. Synthetic local copies are generated by this script (a thumbnail
#   PNG, meta.json and a fig-kiwi stub), plus one bare fig-kiwi file for the refusal.
#
# Every download is pinned by sha256. Downloads are untrusted data: only copied, never run.
set -euo pipefail

ROOT=$(cd "$(dirname "$0")/../.." && pwd)
OUT=${SPECULAR_SKETCH_CORPUS:-$ROOT/tools/corpus/design2}
SK="$OUT/sketch"
FG="$OUT/figma"
SCRATCH="$ROOT/target/agent-corpus/design2-sketch-fetch"
mkdir -p "$SK" "$FG" "$SCRATCH"

die() { echo "fetch-design2-sketch: $*" >&2; exit 1; }

# get NAME URL SHA256
get() {
  local name=$1 url=$2 sum=$3 dest="$SK/$1"
  if [[ -f "$dest" ]] && echo "$sum  $dest" | sha256sum -c --quiet - 2>/dev/null; then
    return
  fi
  echo "fetch-design2-sketch: $name <- $url"
  curl -fsSL --retry 3 -o "$dest.part" "$url" || die "download failed: $url"
  echo "$sum  $dest.part" | sha256sum -c --quiet - || die "sha256 mismatch: $name"
  mv "$dest.part" "$dest"
  printf '%s\t%s\n' "$name" "$url" >> "$OUT/.provenance-sketch.tsv"
}

CARBON=https://raw.githubusercontent.com/carbon-design-system/carbon-design-kit/master
get carbon-v11-white.sketch "$CARBON/Carbon%20Design%20Kit%20-%20v11.0.0/Carbon%20Design%20System%20(White%20theme).sketch" \
  ebf68019a917648118c8ec7d1d0e9d4175bae90488f216509e6174978be73946
get carbon-native-mobile-light.sketch "$CARBON/Carbon%20Design%20Kit%20-%20v11.0.0/native-mobile/Carbon%20Native%20Mobile%20(Light%20theme).sketch" \
  cc8e08e0c46a2a534abb947dd26ed1b682b4683835bee03334b1fb9597a719a2
get carbon-10.1-white.sketch "$CARBON/previous-releases/Carbon%20Design%20Kit%20-%2010.1.0/Carbon%20Design%20System%20(White%20theme).sketch" \
  146b2df3739930433bd2bc79ae86d04995e509ee4baaf40a2085b9ffa9c537c0
get wireframe-kit.sketch https://raw.githubusercontent.com/PC108/Simple-Sketch-Wireframe-Kit/master/wireframe_kit_chevalier.sketch \
  95f79ed080cd7b5257e09c4bd0370249dbf53e88a5324fc1f57c4d06d8450bfe
get old-sqlite-clock.sketch https://raw.githubusercontent.com/dany2or/UI/master/Apps/Clock.sketch \
  50743a829ea0c93812ec18ce43f5504a7894d0c6b249bb62cfdc8c2ea75aed2e

# Sketch reference files: JSON trees zipped into .sketch documents (stored ZIP, by Python's
# zipfile, which the script runs isolated on the downloaded JSON only).
REF=https://raw.githubusercontent.com/sketch-hq/sketch-reference-files/d78b6f36e755770aaae57145c4ca3c0d9339f925/files/123
TREE="$SCRATCH/tree.json"
curl -fsSL --retry 3 -o "$TREE" \
  "https://api.github.com/repos/sketch-hq/sketch-reference-files/git/trees/d78b6f36e755770aaae57145c4ca3c0d9339f925?recursive=1" \
  || die "reference tree"
python3 -I - "$TREE" "$SCRATCH/ref" "$REF" <<'PY'
import json, os, sys, urllib.request
tree, out, base = sys.argv[1:]
paths = [e['path'] for e in json.load(open(tree))['tree']
         if e['type'] == 'blob' and e['path'].startswith('files/123/')]
for p in paths:
    rel = p[len('files/123/'):]
    dest = os.path.join(out, rel)
    if os.path.exists(dest):
        continue
    os.makedirs(os.path.dirname(dest), exist_ok=True)
    for attempt in range(4):
        try:
            with urllib.request.urlopen(base + '/' + urllib.request.quote(rel)) as r:
                data = r.read()
            break
        except OSError:
            if attempt == 3:
                raise
    open(dest, 'wb').write(data)
PY
python3 -I - "$SCRATCH/ref" "$SK" <<'PY'
import os, sys, zipfile
src, out = sys.argv[1:]
for feature in sorted(os.listdir(src)):
    d = os.path.join(src, feature)
    if not os.path.isfile(os.path.join(d, 'document.json')):
        continue
    with zipfile.ZipFile(os.path.join(out, f'ref-{feature}.sketch'), 'w', zipfile.ZIP_DEFLATED) as z:
        for root, _, files in os.walk(d):
            for f in sorted(files):
                full = os.path.join(root, f)
                z.write(full, os.path.relpath(full, d))
PY
printf 'ref-*.sketch\tsketch-hq/sketch-reference-files@d78b6f36e755770aaae57145c4ca3c0d9339f925 files/123 (MIT), zipped\n' >> "$OUT/.provenance-sketch.tsv"

# Synthetic Figma local copies.
python3 -I - "$FG" <<'PY'
import json, os, struct, sys, zipfile, zlib
out = sys.argv[1]
def png(w, h, rgb):
    raw = b''.join(b'\0' + bytes(rgb) * w for _ in range(h))
    def chunk(t, d):
        return struct.pack('>I', len(d)) + t + d + struct.pack('>I', zlib.crc32(t + d) & 0xffffffff)
    return (b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', w, h, 8, 2, 0, 0, 0))
            + chunk(b'IDAT', zlib.compress(raw)) + chunk(b'IEND', b''))
meta = {"client_meta": {"background_color": {"r": 0.96, "g": 0.96, "b": 0.96, "a": 1},
        "thumbnail_size": {"width": 400, "height": 240}}, "file_name": "Synthetic board",
        "exported_at": "2026-10-19T00:00:00.000Z"}
with zipfile.ZipFile(os.path.join(out, 'synthetic-local-copy.fig'), 'w', zipfile.ZIP_STORED) as z:
    z.writestr('canvas.fig', b'fig-kiwi\x0f\x00\x00\x00' + bytes(64))
    z.writestr('thumbnail.png', png(400, 240, (30, 120, 220)))
    z.writestr('meta.json', json.dumps(meta))
with zipfile.ZipFile(os.path.join(out, 'synthetic-deflated.fig'), 'w', zipfile.ZIP_DEFLATED) as z:
    z.writestr('canvas.fig', b'fig-kiwi\x14\x00\x00\x00' + bytes(64))
    z.writestr('thumbnail.png', png(320, 200, (220, 60, 40)))
    z.writestr('meta.json', json.dumps(meta))
open(os.path.join(out, 'bare-canvas.fig'), 'wb').write(b'fig-kiwi\x0f\x00\x00\x00' + bytes(64))
PY

rm -rf "$SCRATCH"
echo "fetch-design2-sketch: $(ls "$SK" | wc -l) sketch, $(ls "$FG" | wc -l) figma files, $(du -sh "$OUT" | cut -f1)"
