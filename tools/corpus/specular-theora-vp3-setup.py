#!/usr/bin/env python3
"""Generate crates/formats/specular-theora/src/vp3_setup.rs: VP3's hard-coded setup data as a
Theora setup header packet, from the text of the Theora specification (Xiph.Org, freely
usable; https://www.theora.org/doc/Theora.pdf, Appendix B: B.2 loop filter limits, B.3
quantization parameters, B.4 the 80 Huffman tables).

Usage: pdftotext -layout Theora.pdf Theora.txt
       specular-theora-vp3-setup.py Theora.txt > crates/formats/specular-theora/src/vp3_setup.rs

The packet is coded exactly as section 6.4 reads it, so the decoder's own setup parser builds
VP3's tables; the script checks every table is a complete prefix code of the 32 tokens.
"""
import re
import sys

text = open(sys.argv[1], encoding="utf-8").read()
app = text[text.index("B.2      Loop Filter Limit Values"):]


def numbers(name, count):
    m = re.search(name + r"\s*=\s*\{", app)
    body = app[m.end():]
    vals = []
    for tok in re.findall(r"-?\d+", body):
        vals.append(int(tok))
        if len(vals) == count:
            return vals
    raise SystemExit(f"{name}: short")


LFLIMS = numbers("LFLIMS", 64)
ACSCALE = numbers("ACSCALE", 64)
DCSCALE = numbers("DCSCALE", 64)
BMS = numbers("BMS", 3 * 64)
BMS = [BMS[i * 64:(i + 1) * 64] for i in range(3)]
# B.3: NQRS = {{1,1,1},{1,1,1}}, QRSIZES all {63}, QRBMIS {{0,0},{1,1},{1,1}} for intra and
# {2,2} for every inter plane.
QRBMIS = [[0, 1, 1], [2, 2, 2]]

# B.4: two tables side by side per page, labelled underneath.
tables = {}
left, right = [], []
row = re.compile(r"^\s*b([01]+)\s+(\d+)\s+b([01]+)\s+(\d+)\s*$")
label = re.compile(r"VP3\.1 Huffman Table Number (\d+)\s+VP3\.1 Huffman Table Number (\d+)")
for line in app[app.index("B.4      Huffman Tables"):].splitlines():
    m = row.match(line)
    if m:
        left.append((m.group(1), int(m.group(2))))
        right.append((m.group(3), int(m.group(4))))
        continue
    m = label.search(line)
    if m:
        tables[int(m.group(1))] = left
        tables[int(m.group(2))] = right
        left, right = [], []
assert sorted(tables) == list(range(80)), sorted(tables)


class W:
    def __init__(self):
        self.bits = []

    def put(self, v, n):
        for i in range(n - 1, -1, -1):
            self.bits.append((v >> i) & 1)

    def bytes(self):
        b = self.bits + [0] * (-len(self.bits) % 8)
        return bytes(int("".join(map(str, b[i:i + 8])), 2) for i in range(0, len(b), 8))


def ilog(a):
    return a.bit_length() if a > 0 else 0


def tree(codes, prefix, w):
    """Writes the subtree under `prefix` in the setup header's order (6.4.4)."""
    for c, t in codes:
        if c == prefix:
            w.put(1, 1)
            w.put(t, 5)
            return
    w.put(0, 1)
    if not any(c.startswith(prefix) for c, _ in codes) or len(prefix) > 32:
        raise SystemExit(f"incomplete code under {prefix!r}")
    tree(codes, prefix + "0", w)
    tree(codes, prefix + "1", w)


w = W()
w.put(0x82, 8)
for ch in b"theora":
    w.put(ch, 8)
w.put(5, 3)
for v in LFLIMS:
    w.put(v, 5)
for scale in (ACSCALE, DCSCALE):
    n = max(v.bit_length() for v in scale)
    w.put(n - 1, 4)
    for v in scale:
        w.put(v, n)
w.put(len(BMS) - 1, 9)
for m in BMS:
    for v in m:
        w.put(v, 8)
bmbits = ilog(len(BMS) - 1)
for qti in range(2):
    for pli in range(3):
        if qti > 0 or pli > 0:
            w.put(1, 1)  # NEWQR: a range of its own
        b = QRBMIS[qti][pli]
        w.put(b, bmbits)
        w.put(63 - 1, ilog(62))  # one range of 63 qi values
        w.put(b, bmbits)
for i in range(80):
    codes = tables[i]
    assert len(codes) == 32 and sorted(t for _, t in codes) == list(range(32)), i
    kraft = sum(2.0 ** -len(c) for c, _ in codes)
    assert abs(kraft - 1.0) < 1e-12, (i, kraft)
    tree(codes, "", w)

packet = w.bytes()
print("// Generated by tools/corpus/specular-theora-vp3-setup.py from the Theora specification,")
print("// Appendix B (VP3's hard-coded loop filter limits, quantization parameters and Huffman")
print("// tables), coded as a Theora setup header (6.4). Do not edit.")
print()
print("/// VP3's setup data as a Theora setup header packet.")
print(f"pub(crate) const VP3_SETUP: [u8; {len(packet)}] = [")
for i in range(0, len(packet), 16):
    print("    " + " ".join(f"0x{b:02x}," for b in packet[i:i + 16]))
print("];")
