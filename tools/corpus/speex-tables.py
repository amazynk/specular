"""Writes specular-speex's src/tables.rs from libspeex 1.2.1's table files (data only).
Usage: python3 -I speex_tables.py LIBSPEEX_DIR OUT"""

import os
import re
import sys

d, out = sys.argv[1], sys.argv[2]
TABLES = [
    ("exc_10_16_table.c", "exc_10_16_table", "EXC_10_16"),
    ("exc_10_32_table.c", "exc_10_32_table", "EXC_10_32"),
    ("exc_20_32_table.c", "exc_20_32_table", "EXC_20_32"),
    ("exc_5_256_table.c", "exc_5_256_table", "EXC_5_256"),
    ("exc_5_64_table.c", "exc_5_64_table", "EXC_5_64"),
    ("exc_8_128_table.c", "exc_8_128_table", "EXC_8_128"),
    ("gain_table.c", "gain_cdbk_nb", "GAIN_NB"),
    ("gain_table_lbr.c", "gain_cdbk_lbr", "GAIN_LBR"),
    ("hexc_10_32_table.c", "hexc_10_32_table", "HEXC_10_32"),
    ("hexc_table.c", "hexc_table", "HEXC"),
    ("high_lsp_tables.c", "high_lsp_cdbk", "HIGH_LSP"),
    ("high_lsp_tables.c", "high_lsp_cdbk2", "HIGH_LSP2"),
    ("lsp_tables_nb.c", "cdbk_nb", "LSP_NB"),
    ("lsp_tables_nb.c", "cdbk_nb_low1", "LSP_NB_LOW1"),
    ("lsp_tables_nb.c", "cdbk_nb_low2", "LSP_NB_LOW2"),
    ("lsp_tables_nb.c", "cdbk_nb_high1", "LSP_NB_HIGH1"),
    ("lsp_tables_nb.c", "cdbk_nb_high2", "LSP_NB_HIGH2"),
]
lines = [
    "//! The Speex codebooks, as data.",
    "//!",
    "//! PROVENANCE: the values of libspeex 1.2.1 (downloads.xiph.org/releases/speex/",
    "//! speex-1.2.1.tar.gz, SHA-256 4b44d4f2b38a370a2d98a78329fefc56a0cf93d1c1be70029217baae6628feea),",
    "//! files `libspeex/exc_*_table.c`, `gain_table.c`, `gain_table_lbr.c`, `hexc_table.c`,",
    "//! `hexc_10_32_table.c`, `high_lsp_tables.c` and `lsp_tables_nb.c`: Copyright (C) 2002",
    "//! Jean-Marc Valin, Xiph.Org Foundation; BSD 3-clause licence (`PROVENANCE.md`). Copied as",
    "//! data; generated by `tools/corpus/speex-tables.py`.",
    "",
]
for f, cname, rname in TABLES:
    src = open(os.path.join(d, f)).read()
    m = re.search(r"\b" + cname + r"\s*\[[^\]]*\]\s*=\s*\{(.*?)\};", src, re.S)
    body = re.sub(r"/\*.*?\*/", "", m.group(1), flags=re.S)
    vals = [v for v in re.split(r"[\s,]+", body.strip()) if v]
    ints = [int(v) for v in vals]
    ty = "u8" if min(ints) >= 0 and max(ints) > 127 else "i8"
    lines.append(f"pub(crate) const {rname}: [{ty}; {len(ints)}] = [")
    for i in range(0, len(ints), 16):
        lines.append("    " + ", ".join(str(v) for v in ints[i : i + 16]) + ",")
    lines.append("];")
    lines.append("")
# The QMF filter of `sb_celp.c` (its floating-point table).
src = open(os.path.join(d, "sb_celp.c")).read()
m = re.search(r"static const float h0\[64\]\s*=\s*\{(.*?)\};", src, re.S)
vals = [v for v in re.split(r"[\s,]+", m.group(1).strip()) if v]
assert len(vals) == 64
lines.append("/// The 64-tap QMF filter (`sb_celp.c`, floating point).")
lines.append("#[allow(clippy::excessive_precision)]")
lines.append("pub(crate) const H0: [f32; 64] = [")
for i in range(0, 64, 4):
    lines.append("    " + ", ".join(vals[i : i + 4]).replace("f", "") + ",")
lines.append("];")
lines.append("")
open(out, "w").write("\n".join(lines))
