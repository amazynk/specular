#!/usr/bin/env bash
# Fetch the GIS formats corpus into tools/corpus/gis-formats/ (gitignored: nothing here is
# committed). The specular-gis format tests read it in place from SPECULAR_GIS_FORMATS_CORPUS
# (a worktree has no corpus of its own), else from tools/corpus/gis-formats, and skip when it
# is absent.
#
# Usage: tools/corpus/fetch-gis-formats.sh [SECTION...]
#   SECTION is a function name below. Default: fetch, unpack, generate, oracle.
#   OUT defaults to $SPECULAR_GIS_FORMATS_CORPUS, else tools/corpus/gis-formats.
#   PYTHON is for generate and oracle only: a venv from wheels alone is enough,
#     python3 -m venv target/gis-formats/venv
#     PIP_NO_CACHE_DIR=1 target/gis-formats/venv/bin/pip install --only-binary=:all: \
#       pyogrio pyarrow rasterio osmium fitdecode shapely pyproj numpy
#   then PYTHON=target/gis-formats/venv/bin/python.
#
# What it covers (about 60 MB), every file pinned by commit (contents API listing, size
# checked) or by SHA-256:
#   gdal/       GDAL autotest data at v3.11.0: FlatGeobuf, GeoParquet and Arrow, GML,
#               OSM XML/PBF, MapInfo TAB/MIF, File Geodatabase (directories and zips,
#               unpacked), NITF, GeoPDF, GPX and KML
#   fgb/        FlatGeobuf's own test data (countries, US counties: 13 MB with an index)
#   geoparquet/ GeoParquet examples and test data; geoarrow-data examples (native, WKB,
#               WKT encodings; Arrow IPC streams)
#   fit/ tcx/   python-fitparse test files; tcxreader example activities
#   osm/        a dated Geofabrik extract of Monaco (ODbL), and its XML twin (generated)
#   gen/        generated by GDAL through rasterio: NITF with JPEG and JPEG 2000 blocks,
#               RPC and IGEOLO; Cloud-Optimized GeoTIFFs for the range-request tests
#   expected/   the oracles in crates/formats/specular-gis/gen: formats_oracle.py (pyogrio,
#               GeoPandas), filegdb_oracle.py and mitab_oracle.py (pyogrio), tracks_oracle.py
#               (fitdecode, ElementTree)
#
# Downloads are untrusted data: this script only copies and unzips them, never runs anything
# from them (the oracle reads them from a script outside the corpus, with -I). Stops when
# free space drops below MIN_FREE_GB (default 8) or the corpus would pass MAX_MB (300).
set -euo pipefail

ROOT=$(cd "$(dirname "$0")/../.." && pwd)
OUT=${SPECULAR_GIS_FORMATS_CORPUS:-$ROOT/tools/corpus/gis-formats}
MIN_FREE_GB=${MIN_FREE_GB:-8}
MAX_MB=${MAX_MB:-300}
PYTHON=${PYTHON:-python3}
mkdir -p "$OUT"

die() { echo "fetch-gis-formats: $*" >&2; exit 1; }

check_space() {
  local avail_kb
  avail_kb=$(df -Pk "$OUT" | awk 'NR==2{print $4}')
  if (( avail_kb < MIN_FREE_GB * 1024 * 1024 )); then
    die "only $((avail_kb / 1024 / 1024)) GB free (< ${MIN_FREE_GB} GB); stopping"
  fi
}

GDAL=OSGeo/gdal:447eb5238bb6ef2837e68bf2ec742c64007b680b   # tag v3.11.0
FGB=flatgeobuf/flatgeobuf:d8b6d6afcfe25b7898ddd721be0cb85c3be276ea
GPQ=opengeospatial/geoparquet:4c9f87e5226e36f2022d6bd7d3c1980debdf7431
GAD=geoarrow/geoarrow-data:e8eaa04487d982398f07713cde527c5c5edeee1e
FIT=dtcooper/python-fitparse:d88bb6997138c38d0c578aeaaf4108df0711d1f6
TCX=alenrajsp/tcxreader:4b0daf5211a7848695918dd84c27ff44891d2e93
MONACO_SHA=27ef6e03d3792f43beb319a5bca7b4ac494e8a62c2ace4bf89c68e5a52b00bd9

fetch() {
  check_space
  rm -f "$OUT/.provenance.tsv"
  python3 -I "$ROOT/tools/corpus/gis-formats-fetch.py" "$OUT" "$MAX_MB" \
    "gh:$GDAL:autotest/ogr/data/flatgeobuf:gdal/fgb" \
    "gh:$GDAL:autotest/ogr/data/parquet:gdal/parquet" \
    "gh:$GDAL:autotest/ogr/data/arrow:gdal/arrow" \
    "gh:$GDAL:autotest/ogr/data/gml:gdal/gml" \
    "gh:$GDAL:autotest/ogr/data/osm:gdal/osm" \
    "gh:$GDAL:autotest/ogr/data/mitab:gdal/mitab" \
    "gh:$GDAL:autotest/ogr/data/filegdb:gdal/filegdb" \
    "gh:$GDAL:autotest/ogr/data/openfilegdb:gdal/openfilegdb" \
    "gh:$GDAL:autotest/gdrivers/data/nitf:gdal/nitf" \
    "gh:$GDAL:autotest/gdrivers/data/pdf:gdal/pdf" \
    "gh:$GDAL:autotest/ogr/data/gpx:gdal/gpx" \
    "gh:$GDAL:autotest/ogr/data/kml:gdal/kml" \
    "gh:$FGB:test/data:fgb:*.fgb" \
    "gh:$GPQ:examples:geoparquet/examples:*.parquet" \
    "gh:$GPQ:test_data:geoparquet/test_data:*.parquet" \
    "gh:$GAD:example/files:geoparquet/geoarrow" \
    "gh:$FIT:tests/files:fit:*.fit" \
    "gh:$FIT:tests/files:fit:*.FIT" \
    "gh:$TCX:example_data:tcx:*.tcx" \
    "url:https://download.geofabrik.de/europe/monaco-250101.osm.pbf:osm/monaco-250101.osm.pbf:$MONACO_SHA"
}

unpack() {           # zipped geodatabases and MapInfo sets, beside the zip
  local z
  while IFS= read -r -d '' z; do
    check_space
    unzip -q -o "$z" -d "${z%.zip}.unzipped" || echo "  could not unzip $z (kept as is)"
  done < <(find "$OUT/gdal/filegdb" "$OUT/gdal/mitab" -name '*.zip' -print0)
}

generate() {         # NITF and COG samples written by GDAL, OSM XML by pyosmium
  "$PYTHON" -I "$ROOT/crates/formats/specular-gis/gen/formats_generate.py" "$OUT"
}

oracle() {
  local gen="$ROOT/crates/formats/specular-gis/gen"
  "$PYTHON" -I "$gen/formats_oracle.py" "$OUT"
  "$PYTHON" -I "$gen/filegdb_oracle.py" "$OUT"
  "$PYTHON" -I "$gen/mitab_oracle.py" "$OUT"
  "$PYTHON" -I "$gen/tracks_oracle.py" "$OUT"
}

main() {
  (( $# )) || set -- fetch unpack generate oracle
  for s in "$@"; do
    declare -F "$s" > /dev/null || die "unknown section $s"
    echo "$s"
    "$s"
  done
  echo "corpus: $(du -sh "$OUT" | cut -f1) in $OUT"
}

main "$@"
