#!/usr/bin/env python3
"""Generate crates/formats/specular-h264/src/spec_tables_444.rs from the H.264 specification.

The CABAC (m, n) initialisation values for ctxIdx 460..1023 (Tables 9-25 to 9-33: the Cb and
Cr residual contexts of 4:4:4 coding and the 8x8 coded_block_flag contexts) are read from the
text of the ITU-T H.264 PDF (`pdftotext -layout`), and checked against the values already in
spec_tables.rs for ctxIdx 70..459 (Tables 9-18 to 9-24), which this parser reads the same way.

Usage: python3 -I tools/corpus/specular-h264-cabac444.py SPEC.txt
SPEC.txt is `pdftotext -layout` of T-REC-H.264 (04/2013 or later). The text is untrusted
data: it is only parsed.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "crates/formats/specular-h264/src/spec_tables_444.rs")
OLD = os.path.join(ROOT, "crates/formats/specular-h264/src/spec_tables.rs")

NUM = r"[−-]?\d+"
ROW = re.compile(r"(?<!\S)(\d{2,4})((?:\s+" + NUM + r"){8})(?=\s|$)")


HEAD = re.compile(r"Table 9-\d+ – Values of variables m and n for ctxIdx from (\d+) to (\d+)")


def parse(text):
    """ctxIdx -> [(m, n)] * 4 for every 4-column row in Tables 9-18 .. 9-33.

    Rows are read table by table. A row numbered outside its table's range is a misprint in
    the published text (Table 9-26 numbers ctxIdx 541 as 641): it is taken for the index 100
    lower when that one is in range and otherwise missing, and reported."""
    start = text.index("Table 9-18 – Values of variables m and n for ctxIdx from 70 to 104\n")
    end = text.index("9.3.1.2     Initialisation process for the arithmetic decoding engine", start)
    body = text[start:end]
    heads = list(HEAD.finditer(body))
    vals = {}
    fixes = []
    for k, h in enumerate(heads):
        lo, hi = int(h.group(1)), int(h.group(2))
        part = body[h.end():heads[k + 1].start() if k + 1 < len(heads) else len(body)]
        for line in part.splitlines():
            for m in ROW.finditer(line):
                idx = int(m.group(1))
                nums = [int(v.replace("−", "-")) for v in m.group(2).split()]
                pairs = [(nums[2 * i], nums[2 * i + 1]) for i in range(4)]
                if not lo <= idx <= hi:
                    if lo <= idx - 100 <= hi:
                        fixes.append((idx, idx - 100))
                        idx -= 100
                    else:
                        continue
                if idx in vals and vals[idx] != pairs:
                    sys.exit(f"ctxIdx {idx}: two different rows")
                vals[idx] = pairs
    for a, b in fixes:
        print(f"note: a row numbered {a} in the table of {b} was read as {b}")
    return vals


def old_table():
    src = open(OLD).read()
    body = src[src.index("pub static CABAC_INIT"):src.index("pub static RANGE_LPS")]
    pairs = [(int(a), int(b)) for a, b in re.findall(r"\((-?\d+),\s*(-?\d+)\)", body)]
    if len(pairs) != 4 * 460:
        sys.exit(f"spec_tables.rs: {len(pairs)} pairs, expected {4 * 460}")
    return [pairs[k * 460:(k + 1) * 460] for k in range(4)]


def main():
    text = open(sys.argv[1], encoding="utf-8").read()
    vals = parse(text)
    old = old_table()
    checked = 0
    for idx in range(70, 460):
        if idx == 276 or idx not in vals:
            continue
        got = vals[idx]
        want = [old[k][idx] for k in range(4)]
        if got != want:
            sys.exit(f"ctxIdx {idx}: spec text {got} != spec_tables.rs {want}")
        checked += 1
    if checked < 380:
        sys.exit(f"only {checked} rows of 70..459 found to check against")
    missing = [i for i in range(460, 1024) if i not in vals]
    if missing:
        sys.exit(f"missing ctxIdx {missing[:10]}...")
    lines = [
        "//! Numeric values of tables defined by ITU-T H.264 (data only, generated by",
        "//! tools/corpus/specular-h264-cabac444.py; do not edit).",
        "//!",
        "//! - [`CABAC_INIT_444`]: (m, n) of Tables 9-25 to 9-33 for ctxIdx 460..1024 (4:4:4 Cb and Cr",
        "//!   residuals, 8x8 coded_block_flag), per init set (0: I slices, 1..=3: cabac_init_idc",
        "//!   0..=2).",
        "",
        "#[rustfmt::skip]",
        "pub static CABAC_INIT_444: [[(i8, i8); 564]; 4] = [",
    ]
    for k in range(4):
        row = [f"({vals[i][k][0]},{vals[i][k][1]})" for i in range(460, 1024)]
        lines.append("    [")
        for j in range(0, len(row), 12):
            lines.append("        " + ",".join(row[j:j + 12]) + ",")
        lines.append("    ],")
    lines.append("];")
    open(OUT, "w").write("\n".join(lines) + "\n")
    print(f"checked {checked} rows against spec_tables.rs; wrote {OUT}")


main()
