#!/usr/bin/env bash
# Fetch and generate the scientific (FITS / XISF) test corpus into tools/corpus/sci/
# (gitignored: nothing here is committed). The specular-fits and specular-xisf tests read it in
# place from SPECULAR_SCI_CORPUS (a worktree has no corpus of its own), else from
# tools/corpus/sci, and skip when it is absent.
#
# Usage: tools/corpus/fetch-sci.sh [SECTION...]
#   SECTION is a function name below (e.g. src_nasa). Default: all sections, then the astropy
#   oracle (src_stats) over everything under fits/.
#   OUT defaults to $SPECULAR_SCI_CORPUS, else tools/corpus/sci.
#   PYTHON (default python3) must have numpy and astropy for the generated files and the
#   oracle, and the `xisf`, `lz4` and `zstandard` packages for the XISF samples. A venv under
#   target/ is fine: python3 -m venv target/sci-venv && target/sci-venv/bin/pip install
#   --no-cache-dir astropy xisf lz4 zstandard; then PYTHON=target/sci-venv/bin/python.
#
# What it covers (about 80 MB, plus 64 MB each for the FITS / XISF speed files):
#   fits/nasa       NASA FITS Support Office samples (HST WFPC2 / FOC / HRS, UIT, EUVE)
#   fits/astropy    astropy's FITS test files at a pinned commit (odd headers, scaling,
#                   compressed images, groups, tables, damaged files)
#   fits/generated  astropy-written files: every BITPIX, BZERO / BSCALE / BLANK, NaN, CONTINUE,
#                   cubes, MEF, and tile compression (Rice, GZIP_1 / 2, HCOMPRESS lossless and
#                   lossy with smoothing, PLIO, quantised floats with dither 1 and 2)
#   fits/expected.tsv  astropy's values for every image plane (the oracle)
#   xisf            generated by crates/formats/specular-xisf/gen/make_samples.py, with its own
#                   expected.tsv
#
# Downloads are untrusted data: this script only copies files, never runs anything from them.
# Scratch space is target/corpus/sci-fetch (deleted afterwards). Stops if free space on
# the target filesystem drops below MIN_FREE_GB (default 6).
set -euo pipefail

ROOT=$(cd "$(dirname "$0")/../.." && pwd)
OUT=${SPECULAR_SCI_CORPUS:-$ROOT/tools/corpus/sci}
SCRATCH="$ROOT/target/corpus/sci-fetch"
MIN_FREE_GB=${MIN_FREE_GB:-6}
PYTHON=${PYTHON:-python3}
export GIT_LFS_SKIP_SMUDGE=1 GIT_TERMINAL_PROMPT=0
mkdir -p "$OUT/fits" "$OUT/xisf" "$SCRATCH"

die() { echo "fetch-sci: $*" >&2; exit 1; }

check_space() {
  local avail_kb
  avail_kb=$(df -Pk "$OUT" | awk 'NR==2{print $4}')
  if (( avail_kb < MIN_FREE_GB * 1024 * 1024 )); then
    die "only $((avail_kb / 1024 / 1024)) GB free (< ${MIN_FREE_GB} GB); stopping"
  fi
}

# provenance RELPATH URL LICENCE
provenance() { printf '%s\t%s\t%s\n' "$1" "$2" "$3" >> "$OUT/.provenance.tsv"; }

# url_file URL DEST LICENCE
url_file() {
  check_space
  mkdir -p "$(dirname "$OUT/$2")"
  curl -fsSL --retry 3 -o "$OUT/$2" "$1"
  provenance "$2" "$1" "$3"
}

# git_files OWNER/REPO COMMIT DEST LICENCE PATH...
# Sparse, blobless, depth-1 fetch of PATH... at COMMIT; copies the FITS files to
# $OUT/DEST/<file name>.
git_files() {
  local repo=$1 commit=$2 dest=$3 lic=$4; shift 4
  local work="$SCRATCH/${repo//\//_}"
  check_space
  rm -rf "$work"
  git init -q "$work"
  git -C "$work" remote add origin "https://github.com/$repo"
  git -C "$work" config core.sparseCheckout true
  git -C "$work" sparse-checkout set --no-cone "$@"
  git -C "$work" fetch -q --depth 1 --filter=blob:none origin "$commit"
  git -C "$work" -c advice.detachedHead=false checkout -q FETCH_HEAD
  local n=0
  mkdir -p "$OUT/$dest"
  while IFS= read -r -d '' f; do
    local rel=${f#"$work"/}
    cp "$f" "$OUT/$dest/$(basename "$rel")"
    provenance "$dest/$(basename "$rel")" "https://github.com/$repo/blob/$commit/$rel" "$lic"
    n=$((n + 1))
  done < <(find "$work" -path "$work/.git" -prune -o -type f \
             \( -iname '*.fits' -o -iname '*.fit' -o -iname '*.fts' -o -iname '*.fz' \) -print0)
  rm -rf "$work"
  echo "  $repo: $n files -> $dest"
}

need_python() {
  "$PYTHON" -I -c "import $1" 2>/dev/null || die "$PYTHON lacks '$1' (see the header for a venv)"
}

# ------------------------------------------------------------------------------- sections

src_nasa() {         # NASA FITS Support Office sample files (public domain, US government)
  local base=https://fits.gsfc.nasa.gov/samples
  for f in WFPC2u5780205r_c0fx.fits WFPC2ASSNu5780205bx.fits FOCx38i0101t_c0f.fits \
           UITfuv2582gc.fits EUVEngc4151imgx.fits HRSz0yd020fm_c2f.fits; do
    url_file "$base/$f" "fits/nasa/$f" "public domain (NASA)"
  done
  echo "  nasa: 6 files -> fits/nasa"
}

src_astropy() {      # astropy's FITS test data, v7.1.0 (BSD-3-Clause)
  git_files astropy/astropy 8f2535d08a6e496134c6d3f63d5fcae67ded35dc fits/astropy BSD-3-Clause \
    'astropy/io/fits/tests/data/*'
}

src_generated() {    # astropy-written FITS (BITPIX, scaling, cubes, MEF, tile compression)
  need_python astropy
  check_space
  "$PYTHON" -I "$ROOT/crates/formats/specular-fits/gen/make_corpus.py" generate "$OUT/fits"
  "$PYTHON" -I "$ROOT/crates/formats/specular-fits/gen/make_corpus.py" big "$OUT/fits"
  provenance fits/generated "crates/formats/specular-fits/gen/make_corpus.py" "generated"
  echo "  generated: $(find "$OUT/fits/generated" -type f | wc -l) files -> fits/generated"
}

src_xisf() {         # generated XISF samples (every sample format, codec, shuffle, layout)
  need_python xisf
  check_space
  "$PYTHON" -I "$ROOT/crates/formats/specular-xisf/gen/make_samples.py" "$OUT/xisf"
  "$PYTHON" -I "$ROOT/crates/formats/specular-xisf/gen/make_samples.py" --big "$OUT/xisf"
  provenance xisf "crates/formats/specular-xisf/gen/make_samples.py" "generated"
  echo "  xisf: $(find "$OUT/xisf" -name '*.xisf' | wc -l) files -> xisf"
}

src_stats() {        # the astropy oracle over everything under fits/
  need_python astropy
  "$PYTHON" -I "$ROOT/crates/formats/specular-fits/gen/make_corpus.py" stats "$OUT/fits"
}

main() {
  if (( $# == 0 )); then
    set -- src_nasa src_astropy src_generated src_xisf src_stats
  fi
  for s in "$@"; do
    declare -F "$s" > /dev/null || die "unknown section $s"
    echo "$s"
    "$s"
  done
  rm -rf "$SCRATCH"
}

main "$@"
