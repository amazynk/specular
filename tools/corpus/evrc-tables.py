#!/usr/bin/env python3
"""Write the EVRC decoder tables of specular-evrc as Rust data.

Usage: tools/corpus/evrc-tables.py SPEC_TXT > crates/formats/specular-evrc/src/tables.rs
  then rustfmt --edition 2024 that file.

SPEC_TXT: `pdftotext -layout` of 3GPP2 C.S0014-A v1.0 (EVRC, Service Option 3), here the
ARIB copy ARIB_STD-T64-C.S0014-Av1.0.pdf
(https://www.arib.or.jp/english/html/overview/doc/Specification/). Appendix B
(Tables 8-1 to 8-15 in that copy) is transcribed: the LSP codebooks, the adaptive
codebook interpolation filter, the fixed codebook gains and the rate 1/8 energy codebook.
Every table is checked for completeness (each index exactly once). Only data is written.
"""

import re
import sys

FLOAT = re.compile(r"-?\d+\.\d+E[+-]\d+")
TOKEN = re.compile(r"-?\d+\.\d+E[+-]\d+|\b\d+\b")


def section(lines, title, end_title):
    start = next(i for i, l in enumerate(lines) if title in l)
    end = next(i for i in range(start + 1, len(lines)) if end_title in lines[i])
    return lines[start + 1:end]


def entries(lines, width, count, base):
    """Rows of `index v1 .. v_width` (several per printed line) -> list by index."""
    out = {}
    for l in lines:
        if not FLOAT.search(l):
            continue
        toks = TOKEN.findall(l)
        i = 0
        while i < len(toks):
            if FLOAT.fullmatch(toks[i]):
                i += 1
                continue
            vals = toks[i + 1:i + 1 + width]
            if len(vals) == width and all(FLOAT.fullmatch(v) for v in vals):
                k = int(toks[i]) - base
                if k in out:
                    sys.exit(f"duplicate index {k + base}")
                out[k] = [float(v) for v in vals]
                i += 1 + width
            else:
                i += 1
    if sorted(out) != list(range(count)):
        missing = sorted(set(range(count)) - set(out))
        sys.exit(f"table incomplete: {len(out)} of {count}, missing {missing[:10]}")
    return [out[k] for k in range(count)]


def lit(v):
    s = repr(v)
    return s if ("." in s or "e" in s) else s + ".0"


def rust_2d(name, rows, doc):
    w = len(rows[0])
    body = "\n".join("    [" + ", ".join(lit(v) for v in r) + "]," for r in rows)
    return f"/// {doc}\npub(crate) static {name}: [[f32; {w}]; {len(rows)}] = [\n{body}\n];\n"


def rust_1d(name, vals, doc):
    body = "\n".join("    " + ", ".join(lit(v) for v in vals[i:i + 6]) + ","
                     for i in range(0, len(vals), 6))
    return f"/// {doc}\npub(crate) static {name}: [f32; {len(vals)}] = [\n{body}\n];\n"


def phases(lines, taps, cols_per_part):
    """Interpolation filters printed as rows n (phase) by columns I(m + taps*n)."""
    rows = [[None] * taps for _ in range(8)]
    m0 = 0
    for part, ncol in enumerate(cols_per_part):
        seen = 0
        for l in lines[part]:
            toks = TOKEN.findall(l)
            if len(toks) == ncol + 1 and all(FLOAT.fullmatch(t) for t in toks[1:]):
                n = int(toks[0])
                for c in range(ncol):
                    rows[n][m0 + c] = float(toks[1 + c])
                seen += 1
        if seen != 8:
            sys.exit(f"filter part {part}: {seen} rows")
        m0 += ncol
    flat = [rows[n][m] for n in range(8) for m in range(taps)]
    if any(v is None for v in flat):
        sys.exit("filter incomplete")
    return flat


def main():
    lines = open(sys.argv[1], encoding="utf-8").read().splitlines()
    out = ["// Generated by tools/corpus/evrc-tables.py from 3GPP2 C.S0014-A v1.0, Appendix B",
           "// (Tables B-1 .. B-15, numbered 8-1 .. 8-15 in the ARIB copy). Data only.",
           "#![allow(clippy::excessive_precision, clippy::unreadable_literal, clippy::approx_constant)]", ""]
    lsp = [
        ("LSP_FULL_1", "Table 8-1.", "Table 8-2.", 2, 64),
        ("LSP_FULL_2", "Table 8-2.", "Table 8-3.", 2, 64),
        ("LSP_FULL_3", "Table 8-3.", "Table 8-4.", 3, 512),
        ("LSP_FULL_4", "Table 8-4.", "Table 8-5.", 3, 128),
        ("LSP_HALF_1", "Table 8-5.", "Table 8-6.", 3, 128),
        ("LSP_HALF_2", "Table 8-6.", "Table 8-7.", 3, 128),
        ("LSP_HALF_3", "Table 8-7.", "Table 8-8.", 4, 256),
        ("LSP_EIGHTH_1", "Table 8-8.", "Table 8-9.", 5, 16),
        ("LSP_EIGHTH_2", "Table 8-9.", "Table 8-10a.", 5, 16),
    ]
    for name, t, e, w, n in lsp:
        rows = entries(section(lines, t, e), w, n, 1)
        out.append(rust_2d(name, rows, f"{t[:-1]}: LSP codebook ({n} x {w}), normalised frequency."))
    ie = phases([section(lines, "Table 8-11a.", "Table 8-11b."),
                 section(lines, "Table 8-11b.", "Table 8-11c."),
                 section(lines, "Table 8-11c.", "Table 8-12.")], 17, [5, 6, 6])
    out.append(rust_1d("IE", ie, "Table 8-11 (B-11): adaptive codebook interpolation filter, "
                       "`IE[m + 17 n]`, cutoff 0.9."))
    g1 = entries(section(lines, "Table 8-12.", "Table 8-13."), 1, 32, 0)
    out.append(rust_1d("GC_FULL", [r[0] for r in g1], "Table 8-12 (B-12): fixed codebook gains, rate 1."))
    g2 = entries(section(lines, "Table 8-13.", "Table 8-14."), 1, 16, 0)
    out.append(rust_1d("GC_HALF", [r[0] for r in g2], "Table 8-13 (B-13): fixed codebook gains, rate 1/2."))
    q = entries(section(lines, "Table 8-15.", "APPENDIX C."), 3, 256, 0)
    out.append(rust_2d("QLOG", q, "Table 8-15 (B-15): rate 1/8 frame energy codebook (log10)."))
    print("\n".join(out))


main()
