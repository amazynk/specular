"""MIP, DCT/DST and LFNST tables of ITU-T H.266 (V4, 01/2026) as Rust.

Usage: python3 -I tools/corpus/vvc-tables.py h266.txt > crates/formats/specular-vvc/src/tables.rs
where h266.txt is `pdftotext -layout` of T-REC-H.266-202601-I!!PDF-E (free from itu.int).
The line ranges below are for that exact PDF and pdftotext 25.x; a different edition needs them redone.
"""
import re,sys
L=open(sys.argv[1],encoding='utf-8').read().replace('−','-').split('\n')
def rows(a,b):
    txt='\n'.join(l for l in L[a:b] if 'Rec. ITU-T' not in l)
    return [[int(x) for x in g.replace(',',' ').split()] for g in re.findall(r'\{([-\d,\s]+)\}',txt)]
def find(pat,start,end=None):
    for i in range(start,end or len(L)):
        if pat in L[i]: return i
    raise Exception(pat)
out=[]
# MIP
mip={}
txt='\n'.join(l for l in L[12175:12733] if 'Rec. ITU-T' not in l)
parts=re.split(r'mipSizeId is equal to (\d) and modeId is equal to (\d+)',txt)
for i in range(1,len(parts),3):
    s,m=int(parts[i]),int(parts[i+1])
    rr=[[int(x) for x in g.replace(',',' ').split()] for g in re.findall(r'\{([-\d,\s]+)\}',parts[i+2])]
    mip.setdefault(s,[]).append(rr)
for s,(n,o,i_) in zip(range(3),[(16,16,4),(8,16,8),(6,64,7)]):
    ms=mip[s]; assert len(ms)==n and all(len(r)==o and all(len(x)==i_ for x in r) for r in ms),s
    out.append(f"/// MIP weights for mipSizeId {s}: [modeId][output][input] (8.4.5.2.4).")
    out.append(f"pub static MIP{s}: [[[u8; {i_}]; {o}]; {n}] = [")
    for r in ms: out.append("  ["+",".join("["+",".join(map(str,x))+"]" for x in r)+"],")
    out.append("];")
# DCT-II 64: blocks Col0to15 and Col16to31 with 64 rows each
b0=find('transMatrixCol0to15 =',20003); b1=find('transMatrixCol16to31 =',b0+1); e=find('(1183)',b1)
c0=rows(b0,b1); c1=rows(b1,e)
assert len(c0)==64 and len(c1)==64 and all(len(r)==16 for r in c0+c1)
M=[[0]*64 for _ in range(64)]  # M[n][m]
for n in range(64):
    for m in range(64):
        if m<16: v=c0[n][m]
        elif m<32: v=c1[n][m-16]
        elif m<48: v=(-1 if n&1 else 1)*c1[n][47-m-16]
        else: v=(-1 if n&1 else 1)*c0[n][63-m]
        M[n][m]=v
out.append("/// DCT-II 64-point matrix as printed: [n (coefficient)][m (sample)] (8.7.4.5).")
out.append("pub static DCT2_64: [[i8; 64]; 64] = [")
for r in M: out.append("  ["+",".join(map(str,r))+"],")
out.append("];")
for tt,name in [(1,'DST7'),(2,'DCT8')]:
    for n in (4,8,16,32):
        s=find(f'trType is equal to {tt} and nTbS is equal to {n},',20003)
        e=s+1
        while e<len(L) and not re.search(r'Otherwise, if trType|^8\.7\.4\.6',L[e]): e+=1
        if n<32:
            r=rows(s,e); assert len(r)==n and all(len(x)==n for x in r),(tt,n,len(r))
        else:
            s1=find('transMatrixCol16to31 =',s)
            a=rows(s,s1); b=rows(s1,e)
            assert len(a)==16 and len(b)==16,(len(a),len(b))
            r=[a[i]+b[i] for i in range(16)]
        out.append(f"/// {name} {n}-point matrix: [n (coefficient)][m (sample)].")
        out.append(f"pub static {name}_{n}: [[i8; {n}]; {min(n,16)}] = [")
        for x in r: out.append("  ["+",".join(map(str,x))+"],")
        out.append("];")
# LFNST
lf16=[[None,None] for _ in range(4)]; lf48=[[None,None] for _ in range(4)]
s0=find('If nTrS is equal to 16, lfnstTrSetIdx is equal to 0, and lfnst_idx is equal to 1',19232)
heads=[]
for i in range(s0,19990):
    mm=re.search(r'nTrS is equal to (\d+), lfnstTrSetIdx is equal to (\d), and lfnst_idx is equal to (\d)',L[i])
    if mm: heads.append((i,int(mm[1]),int(mm[2]),int(mm[3])))
endl=find('8.7.4.4',19900)
for k,(i,ntrs,st,ix) in enumerate(heads):
    e=heads[k+1][0] if k+1<len(heads) else endl
    r=rows(i,e)
    if ntrs==16:
        assert len(r)==16 and all(len(x)==16 for x in r),(ntrs,st,ix,len(r)); lf16[st][ix-1]=r
    else:
        assert len(r)==48 and all(len(x)==16 for x in r),(ntrs,st,ix,len(r),[len(x) for x in r])
        lf48[st][ix-1]=[r[j]+r[16+j]+r[32+j] for j in range(16)]
out.append("/// LFNST 4x4 matrices: [lfnstTrSetIdx][lfnst_idx - 1][j (input)][i (output)] (8.7.4.3).")
out.append("pub static LFNST16: [[[[i8; 16]; 16]; 2]; 4] = [")
for st in range(4):
    out.append(" ["+",".join("["+",".join("["+",".join(map(str,x))+"]" for x in lf16[st][ix])+"]" for ix in range(2))+"],")
out.append("];")
out.append("/// LFNST 8x8 matrices: [lfnstTrSetIdx][lfnst_idx - 1][j (input)][i (output)] (8.7.4.3).")
out.append("pub static LFNST48: [[[[i8; 48]; 16]; 2]; 4] = [")
for st in range(4):
    out.append(" ["+",".join("["+",".join("["+",".join(map(str,x))+"]" for x in lf48[st][ix])+"]" for ix in range(2))+"],")
out.append("];")
print("//! Tables of ITU-T H.266 (V4, 01/2026), extracted from the Recommendation's text.\n//! Generated by tools/corpus/vvc-tables.py from `pdftotext -layout` of the Recommendation; data only.\n")
print("\n".join(out))
