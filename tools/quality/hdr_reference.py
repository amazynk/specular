#!/usr/bin/env python3
"""Reference values for the HDR maths in specular_core::hdr, from independent sources.

* PQ (SMPTE ST 2084) and HLG (BT.2100, 1000 cd/m² display, system gamma 1.2) EOTFs and the
  sRGB EOTF from colour-science;
* BT.2020 / Display P3 → BT.709 matrices from colour-science's RGB colourspaces;
* ISO 21496-1 / Ultra HDR gain-map application and weight, written out from the published
  equations (libultrahdr's `applyGain` and display-boost weight) in float64.

Signals are divided by the BT.2408 reference white (203 cd/m²) like the viewer does.

Writes crates/specular-core/tests/data/hdr_reference.txt (checked by the `hdr_reference`
test). Usage: tools/quality/setup-venv.sh, then
    $CARGO_TARGET_DIR/venv/bin/python tools/quality/hdr_reference.py
"""

import os
import sys

import numpy as np
import colour

REF_WHITE = 203.0
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "crates", "specular-core", "tests", "data", "hdr_reference.txt")


def lines():
    out = ["# kind inputs... = outputs...  (generated by tools/quality/hdr_reference.py, "
           f"colour-science {colour.__version__})"]
    sig = np.linspace(0.0, 1.0, 257)
    for e in sig:
        out.append(f"srgb {e:.9g} = {float(colour.models.eotf_sRGB(e)):.12g}")
        out.append(f"pq {e:.9g} = {float(colour.models.eotf_ST2084(e)) / REF_WHITE:.12g}")
    rng = np.random.default_rng(2100)
    hlg_in = [[e, e, e] for e in sig[::8]] + rng.random((96, 3)).tolist()
    for rgb in hlg_in:
        d = colour.models.eotf_BT2100_HLG(np.array(rgb), L_B=0, L_W=1000) / REF_WHITE
        out.append("hlg " + " ".join(f"{v:.9g}" for v in rgb) + " = "
                   + " ".join(f"{v:.12g}" for v in d))
    bt709 = colour.RGB_COLOURSPACES["ITU-R BT.709"]
    for name, cs in [("bt2020", "ITU-R BT.2020"), ("p3", "Display P3")]:
        m = colour.matrix_RGB_to_RGB(colour.RGB_COLOURSPACES[cs], bt709,
                                     chromatic_adaptation_transform=None)
        out.append(f"matrix {name} = " + " ".join(f"{v:.12g}" for v in m.flatten()))
    # Gain maps: (min, max, gamma, base offset, alt offset, base headroom, alt headroom).
    params = [
        (0.0, 2.0, 1.0, 1 / 64, 1 / 64, 0.0, 2.0),
        (-0.5, 3.3, 2.2, 0.0, 0.0, 0.0, 3.3),
        (-1.0, 1.5, 0.8, 0.01, 0.02, 0.5, 2.5),
        # HDR base mapped down (base headroom above the alternate's).
        (-3.0, 0.0, 1.0, 1 / 64, 1 / 64, 3.0, 0.0),
    ]
    for (gmin, gmax, gamma, ob, oa, hb, ha) in params:
        for display in [1.0, 1.5, 2.0, 4.0, 8.0, 16.0]:
            # Weight (ISO 21496-1 formula 3; libultrahdr: (log2 boost − min) / (max − min)).
            h = np.log2(max(display, 1.0))
            w = np.clip((h - hb) / (ha - hb), 0.0, 1.0) * np.sign(ha - hb)
            out.append(f"weight {gmin} {gmax} {gamma} {ob} {oa} {hb} {ha} {display} = {w:.12g}")
            for base in [0.0, 0.01, 0.18, 0.5, 1.0]:
                for g in [0.0, 0.25, 0.5, 0.75, 1.0]:
                    lg = gmin + (gmax - gmin) * g ** (1.0 / gamma)
                    v = max((base + ob) * 2.0 ** (lg * w) - oa, 0.0)
                    out.append(f"gain {gmin} {gmax} {gamma} {ob} {oa} {hb} {ha} {w:.12g} "
                               f"{base} {g} = {v:.12g}")
    return out


def main():
    text = "\n".join(lines()) + "\n"
    if len(sys.argv) > 1 and sys.argv[1] == "--check":
        same = os.path.exists(OUT) and open(OUT).read() == text
        print("up to date" if same else "differs")
        return 0 if same else 1
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write(text)
    print(f"wrote {OUT}: {text.count(chr(10))} lines")
    return 0


if __name__ == "__main__":
    sys.exit(main())
