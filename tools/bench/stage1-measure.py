#!/usr/bin/env python3
"""Viewer acceptance measurements that need a window: cold start,
idle cost, holding → through a folder, and panning a 200 MP image.

Every run happens inside a private headless sway with private XDG_CONFIG_HOME, XDG_CACHE_HOME,
XDG_DATA_HOME, XDG_STATE_HOME, XDG_RUNTIME_DIR and HOME under ROOT, so nothing reads or writes
the user's settings, caches or desktop session (no session bus either).

    tools/bench/stage1-measure.py [--bin target/release/specular] [--root target/x/stage1] CMD

    startup [--runs 20] [--image FILE]      exec → first present (and first image pixels)
    idle    [--runs 10] [--secs 30] (--image FILE | --folder DIR)
                                            CPU time, wakeups and frames while idle
    hold    [--runs 10] --folder DIR [--count 1000] [-- extra app args]
                                            --bench-hold through DIR (generated by
                                            make-hold-folder.py)
    pan     [--runs 10] [--secs 24] --image FILE
                                            --bench-pan on FILE (e.g. the 200 MP corpus file)
    loupe   [--runs 5] [--secs 10] --image FILE
                                            --bench-loupe on FILE: the tapped loupe jumps to
                                            6 places (time until sharp), then sweeps

Each command prints per-run lines and a summary (median, p95/max and the spread over runs) and
writes the raw per-run JSON to ROOT/results/CMD-*.jsonl.

Headless sway paces frame callbacks with a timer at the output's refresh (60 Hz here) and never
scans out, so present-to-glass latency and real vsync jitter are not measured: numbers are
"frame committed to the compositor", which is what a real display would then show at its next
refresh.
"""

import argparse
import glob
import json
import os
import shutil
import signal
import statistics
import subprocess
import sys
import time

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
CLK_TCK = os.sysconf("SC_CLK_TCK")


def pct(v, q):
    v = sorted(v)
    if not v:
        return float("nan")
    return v[min(len(v) - 1, round((len(v) - 1) * q))]


def summary(name, v, unit="ms"):
    v = [x for x in v if x is not None]
    if not v:
        return f"{name}: no data"
    return (
        f"{name}: median {statistics.median(v):.1f} {unit}, p95 {pct(v, 0.95):.1f}, "
        f"min {min(v):.1f}, max {max(v):.1f} (n={len(v)})"
    )


class Session:
    """A private headless sway and the environment for the app."""

    def __init__(self, root, size=(1920, 1080)):
        self.root = os.path.abspath(root)
        self.size = size
        self.dirs = {k: os.path.join(self.root, "xdg", k) for k in ("run", "config", "cache", "data", "state", "home")}
        for d in self.dirs.values():
            os.makedirs(d, exist_ok=True)
        os.chmod(self.dirs["run"], 0o700)
        self.sway = None

    def base_env(self):
        env = {k: v for k, v in os.environ.items() if k not in ("DISPLAY", "WAYLAND_DISPLAY", "DBUS_SESSION_BUS_ADDRESS", "SPECULAR_LOG", "SPECULAR_LOG_FILE", "SPECULAR_OPEN_REPORT")}
        env.update(
            XDG_RUNTIME_DIR=self.dirs["run"],
            XDG_CONFIG_HOME=self.dirs["config"],
            XDG_CACHE_HOME=self.dirs["cache"],
            XDG_DATA_HOME=self.dirs["data"],
            XDG_STATE_HOME=self.dirs["state"],
            HOME=self.dirs["home"],
        )
        return env

    def __enter__(self):
        conf = os.path.join(self.root, "sway.conf")
        with open(conf, "w") as f:
            f.write(f"xwayland disable\noutput HEADLESS-1 mode {self.size[0]}x{self.size[1]}@60Hz\n")
        env = self.base_env()
        env.update(WLR_BACKENDS="headless", WLR_LIBINPUT_NO_DEVICES="1")
        for s in glob.glob(os.path.join(self.dirs["run"], "wayland-*")):
            os.remove(s)
        self.sway_log = open(os.path.join(self.root, "sway.log"), "w")
        self.sway = subprocess.Popen(["sway", "-c", conf], env=env, stdout=self.sway_log, stderr=subprocess.STDOUT)
        for _ in range(100):
            socks = [s for s in glob.glob(os.path.join(self.dirs["run"], "wayland-*")) if not s.endswith(".lock")]
            if socks:
                self.display = os.path.basename(socks[0])
                time.sleep(0.2)
                return self
            time.sleep(0.05)
        self.__exit__()
        sys.exit("headless sway did not start (see sway.log)")

    def __exit__(self, *a):
        if self.sway:
            self.sway.terminate()
            try:
                self.sway.wait(5)
            except subprocess.TimeoutExpired:
                self.sway.kill()
            self.sway = None

    def app_env(self, **extra):
        env = self.base_env()
        env["WAYLAND_DISPLAY"] = self.display
        env.update(extra)
        return env


def evict(paths):
    """Drops clean page-cache pages of these files (no root needed; mapped pages stay)."""
    for p in paths:
        try:
            fd = os.open(p, os.O_RDONLY)
            os.posix_fadvise(fd, 0, 0, os.POSIX_FADV_DONTNEED)
            os.close(fd)
        except OSError:
            pass


def results_file(root, name):
    d = os.path.join(root, "results")
    os.makedirs(d, exist_ok=True)
    return open(os.path.join(d, f"{name}-{time.strftime('%Y%m%d-%H%M%S')}.jsonl"), "w")


def run_json(cmd, env, timeout):
    """Runs the app, returns the last JSON object on stdout (or None) and stderr's tail."""
    p = subprocess.run(cmd, env=env, capture_output=True, text=True, timeout=timeout)
    out = p.stdout
    start = out.find("{")
    obj = None
    if start >= 0:
        try:
            obj = json.loads(out[start:])
        except json.JSONDecodeError:
            for line in out.splitlines():
                if line.startswith("{"):
                    try:
                        obj = json.loads(line)
                    except json.JSONDecodeError:
                        pass
    return obj, p.stderr[-2000:], p.returncode


# ----- startup ---------------------------------------------------------------------------


def cmd_startup(a, s):
    out = results_file(s.root, "startup" + ("-image" if a.image else "-empty"))
    rows = []
    for i in range(a.runs):
        if a.fresh_cache:
            shutil.rmtree(s.dirs["cache"], ignore_errors=True)
            os.makedirs(s.dirs["cache"])
        if a.evict:
            evict([a.bin] + ([a.image] if a.image else []))
        env = s.app_env(SPECULAR_BENCH_STARTUP="1")
        cmd = [a.bin] + ([a.image] if a.image else [])
        t0 = time.time() * 1000.0
        obj, err, rc = run_json(cmd, env, 30)
        if not obj or "startup" not in obj:
            print(f"run {i}: failed rc={rc}\n{err}")
            continue
        st = obj["startup"]
        at = lambda k: None if st[k] is None else st["main_start_unix_ms"] + st[k] - t0  # noqa: E731
        row = {
            "exec_to_main_ms": st["main_start_unix_ms"] - t0,
            "exec_to_first_present_ms": at("first_present_ms"),
            "exec_to_pixels_ms": at("pixels_ms"),
            "exec_to_text_ms": at("text_ms"),
            **st,
        }
        rows.append(row)
        out.write(json.dumps(row) + "\n")
        fmt = lambda v: "-" if v is None else f"{v:.1f}"  # noqa: E731
        print(
            f"run {i}: exec→main {fmt(row['exec_to_main_ms'])}, →first present {fmt(row['exec_to_first_present_ms'])}, "
            f"→image pixels {fmt(row['exec_to_pixels_ms'])}, →text in real fonts {fmt(row['exec_to_text_ms'])} ms, "
            f"{st['frames']} frames, peak RSS {st['peak_rss_mb']} MB"
        )
        time.sleep(0.3)
    print(f"--- startup {'with ' + os.path.basename(a.image) if a.image else 'without an image'} (target: < 150 ms)")
    if not rows:
        return
    rest = rows[1:] if len(rows) > 2 and not a.fresh_cache else rows
    if rest is not rows:
        print(f"first run (empty pipeline cache): first present {rows[0]['exec_to_first_present_ms']:.1f} ms")
    for k in ("exec_to_main_ms", "exec_to_first_present_ms", "exec_to_pixels_ms", "exec_to_text_ms"):
        print(summary(k, [r[k] for r in rest]))


# ----- idle ------------------------------------------------------------------------------


def proc_sample(pid):
    with open(f"/proc/{pid}/stat") as f:
        st = f.read().rsplit(")", 1)[1].split()
    cpu = (int(st[11]) + int(st[12])) / CLK_TCK  # utime + stime (all threads)
    threads = {}
    for t in glob.glob(f"/proc/{pid}/task/*"):
        try:
            name = open(t + "/comm").read().strip()
            with open(t + "/stat") as f:
                tst = f.read().rsplit(")", 1)[1].split()
            tcpu = (int(tst[11]) + int(tst[12])) / CLK_TCK
            vol = nvol = 0
            for line in open(t + "/status"):
                if line.startswith("voluntary_ctxt_switches"):
                    vol = int(line.split()[1])
                elif line.startswith("nonvoluntary_ctxt_switches"):
                    nvol = int(line.split()[1])
            threads[os.path.basename(t)] = (name, vol + nvol, tcpu)
        except OSError:
            pass
    return cpu, threads


def count_frames(log):
    try:
        with open(log, errors="replace") as f:
            return sum(1 for line in f if " presented in " in line)
    except OSError:
        return 0


def cmd_idle(a, s):
    target = a.image or a.folder
    out = results_file(s.root, "idle-" + ("image" if a.image else "gallery"))
    rows = []
    for i in range(a.runs):
        log = os.path.join(s.root, "idle.log")
        if os.path.exists(log):
            os.remove(log)
        env = s.app_env(SPECULAR_LOG=a.log, SPECULAR_LOG_FILE=log)
        p = subprocess.Popen([a.bin, target], env=env, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        try:
            # Settle: no frame for 3 s and under 1% CPU over the last 3 s (thumbnails, fonts,
            # the sharp image, tiles and the prefetch of the neighbours are done).
            t_start = time.time()
            last_n, last_change = -1, time.time()
            cpu_hist = []
            while time.time() - t_start < a.settle_max:
                n = count_frames(log)
                cpu_hist.append((time.time(), proc_sample(p.pid)[0]))
                old = [c for c in cpu_hist if c[0] <= cpu_hist[-1][0] - 3.0]
                quiet = bool(old) and (cpu_hist[-1][1] - old[-1][1]) / (cpu_hist[-1][0] - old[-1][0]) < 0.01
                if n != last_n:
                    last_n, last_change = n, time.time()
                elif time.time() - last_change > 3.0 and quiet:
                    break
                time.sleep(0.25)
            settle = time.time() - t_start
            f0 = count_frames(log)
            c0, th0 = proc_sample(p.pid)
            t0 = time.time()
            time.sleep(a.secs)
            c1, th1 = proc_sample(p.pid)
            t1 = time.time()
            f1 = count_frames(log)
        finally:
            p.send_signal(signal.SIGTERM)
            try:
                p.wait(10)
            except subprocess.TimeoutExpired:
                p.kill()
                p.wait()
        dt = t1 - t0
        per_thread = {}
        cpu_thread = {}
        for tid, (name, n, c) in th1.items():
            _, n0, cz = th0.get(tid, (name, 0, 0.0))
            if n - n0:
                per_thread[name] = per_thread.get(name, 0) + n - n0
            if c - cz:
                cpu_thread[name] = round(cpu_thread.get(name, 0) + 1000 * (c - cz))
        wake = sum(per_thread.values())
        row = {
            "settle_s": settle,
            "cpu_pct": 100.0 * (c1 - c0) / dt,
            "cpu_ms": 1000.0 * (c1 - c0),
            "wakeups_per_s": wake / dt,
            "frames": f1 - f0,
            "frames_per_s": (f1 - f0) / dt,
            "threads": len(th1),
            "wakeups_by_thread": dict(sorted(per_thread.items(), key=lambda kv: -kv[1])[:8]),
            "cpu_ms_by_thread": dict(sorted(cpu_thread.items(), key=lambda kv: -kv[1])[:8]),
        }
        rows.append(row)
        out.write(json.dumps(row) + "\n")
        print(
            f"run {i}: settled after {settle:.1f} s; CPU {row['cpu_ms']:.0f} ms in {dt:.0f} s ({row['cpu_pct']:.3f}%), "
            f"{row['wakeups_per_s']:.1f} wakeups/s, {row['frames']} frames, {row['threads']} threads; wakeups {row['wakeups_by_thread']}; CPU ms {row['cpu_ms_by_thread']}"
        )
    print(f"--- idle on {'an image' if a.image else 'the gallery'} over {a.secs} s (target: ~0% CPU, no redraws)")
    for k, u in (("cpu_pct", "%"), ("wakeups_per_s", "/s"), ("frames", "frames")):
        print(summary(k, [r[k] for r in rows], u))


# ----- hold and pan -----------------------------------------------------------------------


def bench(a, s, extra, name):
    out = results_file(s.root, name)
    rows = []
    for i in range(a.runs):
        cmd = [a.bin, "--size", f"{s.size[0]}x{s.size[1]}"] + extra + a.extra
        env = s.app_env()
        if a.log:
            # The last run's log (for "slow frame" breakdowns and the like).
            env.update(SPECULAR_LOG=a.log, SPECULAR_LOG_FILE=os.path.join(s.root, f"{name}.log"))
        obj, err, rc = run_json(cmd, env, 400)
        if not obj:
            print(f"run {i}: failed rc={rc}\n{err}")
            continue
        rows.append(obj)
        out.write(json.dumps(obj) + "\n")
        yield i, obj
    return rows


def cmd_hold(a, s):
    files = sorted(f for f in os.listdir(a.folder) if not f.endswith(".part"))
    first = os.path.join(a.folder, files[0])
    keys = {k: [] for k in ("shown_s", "passed_s", "frame_p50", "frame_p95", "frame_max", "over16", "work_p95", "work_max", "work_over16", "frames", "gap_max", "gaps_over_25", "stall_frames", "rss", "vram", "lat_p50", "lat_p95", "no_pixels", "settle")}
    for i, o in bench(a, s, ["--bench-open", first, "--bench-hold", str(a.count)], "hold"):
        h = o.get("hold", {})
        if not h:
            print(f"run {i}: no hold section")
            continue
        fc = h["frame_cpu_ms"]
        vals = dict(
            shown_s=h["images_shown_per_s"], passed_s=h["images_passed_per_s"], frame_p50=fc["p50"], frame_p95=fc["p95"],
            frame_max=fc["max"], over16=fc["over_16_7"], frames=h["frames"], gap_max=h["present_gap_ms"]["max"],
            gaps_over_25=h["present_gaps_over_25"], stall_frames=h["frames_over_50"], rss=o["peak_rss_mb"], vram=h["vram_max_mb"],
            lat_p50=h["pixels_latency_ms"]["p50"], lat_p95=h["pixels_latency_ms"]["p95"], no_pixels=h["frames_without_pixels"],
            settle=h["settle_sharp_ms"],
        )
        # Without the surface acquire (a GPU or compositor wait); older builds lack it.
        fw = h.get("frame_work_ms", {})
        vals.update(work_p95=fw.get("p95"), work_max=fw.get("max"), work_over16=fw.get("over_16_7"))
        for k, v in vals.items():
            keys[k].append(v)
        print(
            f"run {i}: {h['images_passed']} passed in {h['held_s']} s, {h['images_shown']} shown ({vals['shown_s']}/s); "
            f"frame CPU p50 {fc['p50']} p95 {fc['p95']} max {fc['max']} ms, {fc['over_16_7']}/{h['frames']} over 16.7 "
            f"(without acquire: p95 {vals['work_p95']} max {vals['work_max']}, {vals['work_over16']} over 16.7); "
            f"present gap max {vals['gap_max']} ms ({vals['gaps_over_25']} over 25, {h['present_gap_ms']['over_50']} over 50); "
            f"frames without pixels {vals['no_pixels']}; peak RSS {vals['rss']} MB, VRAM {vals['vram']} MB"
        )
    print(f"--- hold → through {a.count} files (targets: every frame shows an image, no stall over 50 ms, no frame over 16.7 ms)")
    for k, v in keys.items():
        print(summary(k, v, ""))


def cmd_pan(a, s):
    keys = {}
    for i, o in bench(a, s, ["--bench-open", a.image, "--bench-pan", str(a.secs)], "pan"):
        p = o.get("pan")
        if not p:
            print(f"run {i}: no pan section")
            continue
        line = [f"run {i}: rss {o['peak_rss_mb']} MB"]
        for half in ("pan_100", "pan_zoom"):
            h = p[half]
            vals = {
                f"{half}.fps": h["fps"],
                f"{half}.cpu_p50": h["frame_cpu_ms"]["p50"],
                f"{half}.cpu_p95": h["frame_cpu_ms"]["p95"],
                f"{half}.cpu_max": h["frame_cpu_ms"]["max"],
                f"{half}.cpu_over_16_7": h["frame_cpu_ms"]["over_16_7"],
                f"{half}.interval_p95": h["present_interval_ms"]["p95"],
                f"{half}.interval_max": h["present_interval_ms"]["max"],
                f"{half}.intervals_over_25": h["present_interval_ms"]["over_25"],
                f"{half}.frames_tiles_missing": h["frames_with_tiles_missing"],
            }
            for k, v in vals.items():
                keys.setdefault(k, []).append(v)
            line.append(
                f"{half}: {h['frames']} frames {h['fps']} fps, CPU p50 {h['frame_cpu_ms']['p50']} p95 {h['frame_cpu_ms']['p95']} "
                f"max {h['frame_cpu_ms']['max']}, interval p95 {h['present_interval_ms']['p95']} max {h['present_interval_ms']['max']}, "
                f"{h['frames_with_tiles_missing']} frames with tiles missing"
            )
        keys.setdefault("peak_rss_mb", []).append(o["peak_rss_mb"])
        print("; ".join(line))
    print(f"--- pan/zoom {os.path.basename(a.image)} for {a.secs} s (target: display refresh, 60 Hz here)")
    for k, v in keys.items():
        print(summary(k, v, ""))


def cmd_loupe(a, s):
    keys = {}
    for i, o in bench(a, s, ["--bench-open", a.image, "--bench-loupe", str(a.secs)], "loupe"):
        lp = o.get("loupe")
        if not lp:
            print(f"run {i}: no loupe section")
            continue
        w = lp["sweep"]
        vals = {
            "jump_first_frame_p50_ms": lp["jump_first_frame_p50_ms"],
            "jump_sharp_p50_ms": lp["jump_sharp_p50_ms"],
            "jump_sharp_max_ms": lp["jump_sharp_max_ms"],
            "sweep_fps": w["fps"],
            "events_per_s": w["events_per_s"],
            "frame_cpu_p50": w["frame_cpu_ms"]["p50"],
            "frame_cpu_p95": w["frame_cpu_ms"]["p95"],
            "frame_cpu_max": w["frame_cpu_ms"]["max"],
            "interval_p95": w["present_interval_ms"]["p95"],
            "interval_max": w["present_interval_ms"]["max"],
            "intervals_over_25": w["over_25"],
            "request_tiles_p50": w["request_tiles_ms_per_frame"]["p50"],
            "request_tiles_max": w["request_tiles_ms_per_frame"]["max"],
            "scene_p50": w["scene_ms"]["p50"],
            "submit_present_p50": w["submit_present_ms"]["p50"],
            "frames_not_sharp_pct": 100.0 * w["frames_loupe_not_sharp"] / max(1, w["frames"]),
            "jobs_started": w["tile_jobs_started"],
            "jobs_cancelled": w["tile_jobs_cancelled"],
            "loupe_decode_p50": w["loupe_decode_ms"]["p50"],
            "loupe_upload_p50": w["loupe_upload_ms"]["p50"],
            "peak_rss_mb": o["peak_rss_mb"],
        }
        for k, v in vals.items():
            keys.setdefault(k, []).append(v)
        print(f"run {i}: " + ", ".join(f"{k} {v:.1f}" for k, v in vals.items()))
    print(f"--- loupe {os.path.basename(a.image)}, sweep {a.secs} s (target: display refresh, 60 Hz here)")
    for k, v in keys.items():
        print(summary(k, v, ""))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--bin", default=os.path.join(REPO, "target/release/specular"))
    ap.add_argument("--root", default=os.path.join(REPO, "target/stage1-measure"))
    ap.add_argument("--size", default="1920x1080")
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("startup")
    p.add_argument("--runs", type=int, default=20)
    p.add_argument("--image")
    p.add_argument("--evict", action="store_true", help="drop the binary's and image's page-cache pages before each run")
    p.add_argument("--fresh-cache", action="store_true", help="empty XDG_CACHE_HOME before each run (first launch)")
    p = sub.add_parser("idle")
    p.add_argument("--runs", type=int, default=10)
    p.add_argument("--secs", type=float, default=30)
    p.add_argument("--settle-max", type=float, default=120)
    p.add_argument("--log", default="render:debug", help="SPECULAR_LOG filter (render:debug is needed to count frames)")
    g = p.add_mutually_exclusive_group(required=True)
    g.add_argument("--image")
    g.add_argument("--folder")
    p = sub.add_parser("hold")
    p.add_argument("--runs", type=int, default=10)
    p.add_argument("--folder", required=True)
    p.add_argument("--count", type=int, default=1000)
    p.add_argument("--log", help="SPECULAR_LOG filter; the last run's log goes to ROOT/CMD.log")
    p.add_argument("extra", nargs="*")
    p = sub.add_parser("pan")
    p.add_argument("--runs", type=int, default=10)
    p.add_argument("--secs", type=float, default=24)
    p.add_argument("--image", required=True)
    p.add_argument("--log", help="SPECULAR_LOG filter; the last run's log goes to ROOT/CMD.log")
    p.add_argument("extra", nargs="*")
    p = sub.add_parser("loupe")
    p.add_argument("--runs", type=int, default=5)
    p.add_argument("--secs", type=float, default=10)
    p.add_argument("--image", required=True)
    p.add_argument("--log", help="SPECULAR_LOG filter; the last run's log goes to ROOT/CMD.log")
    p.add_argument("extra", nargs="*")
    a = ap.parse_args()
    a.bin = os.path.abspath(a.bin)
    for k in ("image", "folder"):
        if getattr(a, k, None):
            setattr(a, k, os.path.abspath(getattr(a, k)))
    size = tuple(int(x) for x in a.size.split("x"))
    with Session(a.root, size) as s:
        {"startup": cmd_startup, "idle": cmd_idle, "hold": lambda a, s: cmd_hold(a, s), "pan": cmd_pan, "loupe": cmd_loupe}[a.cmd](a, s)


if __name__ == "__main__":
    main()
