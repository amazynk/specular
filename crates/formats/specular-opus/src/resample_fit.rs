//! Measured SILK upsampler kernels (8, 12 and 16 kHz to 48 kHz), as impulse responses at
//! 48 kHz (`out[t] = Σ k[m] xz[t - m]`, the input zero-stuffed). RFC 6716 leaves the
//! upsampler to the implementation (section 4.2.9), and the reference decoder's is not a
//! linear-phase one: our earlier Kaiser sinc agreed with its decodes only to 17–20 dB on
//! the SILK test vectors, the error in its phase between 4 and 8 kHz.
//!
//! Each kernel is that sinc followed by the least-squares correction mapping our decode to
//! the reference decoder's: measured from decoded output only (`resample_study.rs`, which
//! writes this table with `SPECULAR_OPUS_FIT_OUT`). `FIT_8` and `FIT_12` from RFC 8251 test
//! vectors 2 and 3 and the decodes shipped with them. `FIT_16` from libopus's decodes of
//! broadband SILK wideband streams (noise, a chirp, moving tones;
//! tools/corpus/specular-opus-wb.sh, `SPECULAR_OPUS_WB_CORPUS`): fitted on vector 4 alone it
//! learned that speech's own SILK differences below 3 kHz (-0.02 dB at 700 Hz), which cost
//! a steady tone 4 dB; fitted on the broadband set it is flat there to 0.015 dB and keeps
//! the same 4–8 kHz phase, and all RFC vectors are held out.
//!
//! Refitted with 401-tap corrections once our SILK reconstruction matched the reference's
//! sample for sample at the internal rate (`silk_study.rs`): the fits now see only the
//! upsampler. SILK and hybrid vectors 2–6 and 12: 58–63 dB at 48 kHz (41–45 dB before).

