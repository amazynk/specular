//! Specular's own EVRC speech decoder.
//!
//! EVRC (Enhanced Variable Rate Codec, 3GPP2 C.S0014-A, TIA/EIA IS-127, CDMA Service
//! Option 3): 8 kHz speech in 20 ms frames at rate 1 (171 bits), rate 1/2 (80 bits) and
//! rate 1/8 (16 bits), as stored in QCP files (RFC 3625) and 3GPP2 `sevc` tracks
//! (C.S0050-B): one rate byte, then the packet.
//!
//! The decoder follows the floating-point description of C.S0014-A §5: RCELP adaptive
//! codebook mapped to the interpolated delay contour, the ACELP fixed codebook, rate 1/8
//! noise excitation, frame-erasure processing (delay contour reconstruction, gain decay
//! and fade) and the adaptive postfilter (§5.4). The decoding logic is our own; the tables
//! are data transcribed from the specification's Appendix B (`tables.rs`, generated by
//! `tools/corpus/evrc-tables.py`).
//!
//! Patents: EVRC's essential patents date from 1994–1996 and have expired.

#![deny(unsafe_code)]
#![allow(clippy::needless_range_loop)]

mod tables;

use tables::{
    GC_FULL, GC_HALF, IE, LSP_EIGHTH_1, LSP_EIGHTH_2, LSP_FULL_1, LSP_FULL_2, LSP_FULL_3,
    LSP_FULL_4, LSP_HALF_1, LSP_HALF_2, LSP_HALF_3, QLOG,
};

/// Samples a frame decodes to.
pub const FRAME_SAMPLES: usize = 160;
/// EVRC's sample rate.
pub const SAMPLE_RATE: u32 = 8000;

/// A packet's rate (RFC 3558 / RFC 3625 rate byte).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Rate {
    /// Blanked (signalling took the frame): erasure processing.
    Blank,
    Eighth,
    Half,
    Full,
    /// Lost or damaged; also the rate 1/4 byte, which EVRC never sends.
    Erasure,
}

impl Rate {
    /// The rate of a rate byte (0 blank, 1 eighth, 2 quarter, 3 half, 4 full, 14 erasure).
    pub fn from_byte(b: u8) -> Option<Rate> {
        Some(match b {
            0 => Rate::Blank,
            1 => Rate::Eighth,
            2 | 14 => Rate::Erasure,
            3 => Rate::Half,
            4 => Rate::Full,
            _ => return None,
        })
    }

    /// The rate of a packet stored without its rate byte, by its length.
    pub fn from_len(n: usize) -> Option<Rate> {
        Some(match n {
            0 => Rate::Blank,
            2 => Rate::Eighth,
            10 => Rate::Half,
            22 => Rate::Full,
            _ => return None,
        })
    }

    /// Bytes after the rate byte.
    pub fn payload_bytes(self) -> usize {
        match self {
            Rate::Blank | Rate::Erasure => 0,
            Rate::Eighth => 2,
            Rate::Half => 10,
            Rate::Full => 22,
        }
    }
}

/// The length of a stored packet (rate byte included) from its rate byte.
pub fn packet_len(rate_byte: u8) -> Option<usize> {
    match rate_byte {
        0 | 14 => Some(1),
        1 => Some(3),
        2 => Some(6),
        3 => Some(11),
        4 => Some(23),
        _ => None,
    }
}

/// Subframe lengths (§5.2.3).
const SUB: [usize; 3] = [53, 53, 54];
/// LSP interpolation per subframe (§5.2.3.1).
const MU: [f32; 3] = [0.1667, 0.5, 0.8333];
/// Delay interpolation (4.5.4.5-2).
const FD: [f32; 5] = [0.0, 0.3313, 0.6625, 1.0, 1.0];
/// Erasure delays when the last frame was unvoiced (5.2.3.4-2).
const D_RND: [f32; 5] = [55.0, 80.0, 39.0, 71.0, 33.0];
/// Adaptive codebook gains (Table 4.5.4-1).
const GP_CB: [f32; 8] = [0.0, 0.3, 0.55, 0.7, 0.8, 0.9, 1.0, 1.2];
/// Adaptive codebook memory (E(n), -128 <= n < 0).
const MEM: usize = 128;
/// The postfilter's residual history (longest delay 120 + 3).
const PF_HIST: usize = 128;

/// Decoder rate (frames decode as full, half or eighth).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Dr {
    Full,
    Half,
    Eighth,
}

/// MSB-first bit reader over a packet (§4.8: bit index 0 is the most significant).
struct Bits<'a> {
    d: &'a [u8],
    pos: usize,
}

impl Bits<'_> {
    fn get(&mut self, n: u32) -> u32 {
        let mut v = 0;
        for _ in 0..n {
            let byte = self.d.get(self.pos / 8).copied().unwrap_or(0);
            v = (v << 1) | u32::from((byte >> (7 - self.pos % 8)) & 1);
            self.pos += 1;
        }
        v
    }
}

#[derive(Clone, Copy, Default)]
struct Sub {
    acbg: usize,
    fcbs: [u32; 4],
    fcbg: usize,
}

/// One frame's fields.
#[derive(Clone, Copy, Default)]
struct Frame {
    lpcflag: bool,
    lsp: [usize; 4],
    delay: u32,
    ddelay: u32,
    sub: [Sub; 3],
    fgidx: usize,
}

fn parse(rate: Dr, p: &[u8]) -> Frame {
    let mut b = Bits { d: p, pos: 0 };
    let mut f = Frame::default();
    match rate {
        Dr::Full => {
            f.lpcflag = b.get(1) != 0;
            for (k, n) in [6, 6, 9, 7].into_iter().enumerate() {
                f.lsp[k] = b.get(n) as usize;
            }
            f.delay = b.get(7);
            f.ddelay = b.get(5);
            for s in &mut f.sub {
                s.acbg = b.get(3) as usize;
                for (i, n) in [8, 8, 8, 11].into_iter().enumerate() {
                    s.fcbs[i] = b.get(n);
                }
                s.fcbg = b.get(5) as usize;
            }
        }
        Dr::Half => {
            for (k, n) in [7, 7, 8].into_iter().enumerate() {
                f.lsp[k] = b.get(n) as usize;
            }
            f.delay = b.get(7);
            for s in &mut f.sub {
                s.acbg = b.get(3) as usize;
                s.fcbs[0] = b.get(10);
                s.fcbg = b.get(4) as usize;
            }
        }
        Dr::Eighth => {
            f.lsp[0] = b.get(4) as usize;
            f.lsp[1] = b.get(4) as usize;
            f.fgidx = b.get(8) as usize;
        }
    }
    f
}

/// Quantised LSPs from the codebook indices (4.4.5-1); `None` unless strictly ascending.
fn decode_lsp(rate: Dr, idx: &[usize; 4]) -> Option<[f32; 10]> {
    let mut w = [0f32; 10];
    let mut at = 0;
    let mut put = |v: &[f32]| {
        w[at..at + v.len()].copy_from_slice(v);
        at += v.len();
    };
    match rate {
        Dr::Full => {
            put(&LSP_FULL_1[idx[0] & 63]);
            put(&LSP_FULL_2[idx[1] & 63]);
            put(&LSP_FULL_3[idx[2] & 511]);
            put(&LSP_FULL_4[idx[3] & 127]);
        }
        Dr::Half => {
            put(&LSP_HALF_1[idx[0] & 127]);
            put(&LSP_HALF_2[idx[1] & 127]);
            put(&LSP_HALF_3[idx[2] & 255]);
        }
        Dr::Eighth => {
            put(&LSP_EIGHTH_1[idx[0] & 15]);
            put(&LSP_EIGHTH_2[idx[1] & 15]);
        }
    }
    w.windows(2).all(|p| p[0] < p[1]).then_some(w)
}

fn lsp_spread() -> [f32; 10] {
    std::array::from_fn(|k| 0.048 * (k + 1) as f32)
}

/// LSPs (normalised frequency) to direct-form LPC `a(1..=10)` with A(z) = 1 - sum a z^-k
/// (§4.2.2.2).
fn lsp_to_lpc(w: &[f32; 10]) -> [f32; 10] {
    // product of the second-order sections over the odd (P) and even (Q) frequencies
    let poly = |odd: bool| {
        let mut c = [0f64; 12];
        c[0] = 1.0;
        let mut len = 1;
        for j in 0..5 {
            let f = f64::from(w[2 * j + usize::from(!odd)]);
            let k = -2.0 * (2.0 * std::f64::consts::PI * f).cos();
            for i in (0..len + 2).rev() {
                let mut v = c[i];
                if i >= 1 {
                    v += k * c[i - 1];
                }
                if i >= 2 {
                    v += c[i - 2];
                }
                c[i] = v;
            }
            len += 2;
        }
        c
    };
    let p = poly(true);
    let q = poly(false);
    let mut a = [0f32; 10];
    for i in 1..=10 {
        // P_A = (1 + z^-1) P, Q_A = (1 - z^-1) Q
        let pa = p[i] + p[i - 1];
        let qa = q[i] - q[i - 1];
        a[i - 1] = (-(pa + qa) / 2.0) as f32;
    }
    a
}

/// The uniform and Gaussian generators of §4.7.
#[derive(Clone)]
struct Rng {
    seed: i64,
}

impl Rng {
    fn uniform(&mut self) -> f64 {
        let mut s = (self.seed ^ 23_148_373) & 0x7fff_ffff;
        let t = s / 127_773;
        s = 16_807 * (s - t * 127_773) - 2_836 * t;
        if s < 0 {
            s += 2_147_483_647;
        }
        let r = s as f64 / 2_147_483_647.0;
        self.seed = s ^ 23_148_373;
        r
    }

    fn gauss_pair(&mut self) -> (f32, f32) {
        for _ in 0..64 {
            let v1 = 2.0 * self.uniform() - 1.0;
            let v2 = 2.0 * self.uniform() - 1.0;
            let rsq = v1 * v1 + v2 * v2;
            if rsq < 1.0 && rsq > 0.0 {
                let fac = (-2.0 * rsq.ln() / rsq).sqrt();
                return ((v1 * fac) as f32, (v2 * fac) as f32);
            }
        }
        (0.0, 0.0)
    }
}

/// Unit-variance Gaussian noise, one value at a time.
#[derive(Clone)]
struct Noise {
    rng: Rng,
    spare: Option<f32>,
}

impl Noise {
    fn next(&mut self) -> f32 {
        if let Some(v) = self.spare.take() {
            return v;
        }
        let (a, b) = self.rng.gauss_pair();
        self.spare = Some(b);
        a
    }
}

/// The adaptive postfilter's memories (§5.4).
#[derive(Clone)]
struct Postfilter {
    last_s: f32,
    /// Tilted speech history for the residual filter, newest last.
    st_hist: [f32; 10],
    /// Residual history, newest last.
    res: [f32; PF_HIST],
    /// Short-term postfilter output history, newest last.
    out_hist: [f32; 10],
}

impl Postfilter {
    fn new() -> Self {
        Postfilter {
            last_s: 0.0,
            st_hist: [0.0; 10],
            res: [0.0; PF_HIST],
            out_hist: [0.0; 10],
        }
    }

    fn run(&mut self, s: &[f32], a: &[f32; 10], rate: Dr, delay: Option<f32>, out: &mut Vec<f32>) {
        let l = s.len();
        let (tilt, g1, g2) = match rate {
            Dr::Full => (0.20, 0.57, 0.75),
            Dr::Half => (0.35, 0.50, 0.75),
            Dr::Eighth => (0.0, 0.57, 0.57),
        };
        let r: f32 = s.windows(2).map(|p| p[0] * p[1]).sum();
        let mu = if r >= 0.0 { tilt } else { 0.0 };
        // tilt compensation
        let mut st = [0f32; 54];
        let mut prev = self.last_s;
        for n in 0..l {
            st[n] = s[n] - mu * prev;
            prev = s[n];
        }
        self.last_s = prev;
        // short-term residual filter A(z / g1)
        let mut a1 = [0f32; 10];
        let mut a2 = [0f32; 10];
        let (mut p1, mut p2) = (1f32, 1f32);
        for k in 0..10 {
            p1 *= g1;
            p2 *= g2;
            a1[k] = a[k] * p1;
            a2[k] = a[k] * p2;
        }
        let mut hist = [0f32; 64];
        hist[..10].copy_from_slice(&self.st_hist);
        hist[10..10 + l].copy_from_slice(&st[..l]);
        // residual: history then this subframe
        let mut e = [0f32; PF_HIST + 54];
        e[..PF_HIST].copy_from_slice(&self.res);
        for n in 0..l {
            let mut v = hist[10 + n];
            for k in 0..10 {
                v -= a1[k] * hist[10 + n - k - 1];
            }
            e[PF_HIST + n] = v;
        }
        self.st_hist.copy_from_slice(&hist[l..l + 10]);
        // long-term postfilter around the decoded delay
        let mut sp = [0f32; 54];
        sp[..l].copy_from_slice(&e[PF_HIST..PF_HIST + l]);
        if let Some(d) = delay {
            // the best integer delay within 3 of the decoded one (5.4.3-3)
            let di = d.round() as i64;
            let mut best = (f32::MIN, 0usize);
            for dd in (di - 3)..=(di + 3) {
                let dd = dd.clamp(1, PF_HIST as i64) as usize;
                let c: f32 = (0..l).map(|n| e[PF_HIST + n] * e[PF_HIST + n - dd]).sum();
                if c > best.0 {
                    best = (c, dd);
                }
            }
            let (num, dopt) = best;
            if dopt > 0 {
                let den: f32 = (0..l).map(|n| e[PF_HIST + n - dopt].powi(2)).sum();
                let gp = if den > 0.0 { num / den } else { 0.0 };
                let g = if gp >= 1.0 {
                    0.5
                } else if gp >= 0.5 {
                    0.5 * gp
                } else {
                    0.0
                };
                for n in 0..l {
                    sp[n] += g * e[PF_HIST + n - dopt];
                }
            }
        }
        self.res.copy_from_slice(&e[l..l + PF_HIST]);
        // short-term postfilter 1 / A(z / g2), once to find the gain, then for real
        let filt = |input: &[f32], mem: &mut [f32; 10], o: &mut [f32]| {
            for n in 0..input.len() {
                let mut v = input[n];
                for k in 0..10 {
                    v += a2[k] * mem[9 - k];
                }
                mem.copy_within(1.., 0);
                mem[9] = v;
                o[n] = v;
            }
        };
        let mut tmp = [0f32; 54];
        let mut m = self.out_hist;
        filt(&sp[..l], &mut m, &mut tmp[..l]);
        let es: f32 = s.iter().map(|v| v * v).sum();
        let et: f32 = tmp[..l].iter().map(|v| v * v).sum();
        let gs = if et > 0.0 {
            (es / et).sqrt().min(1.0)
        } else {
            1.0
        };
        for v in &mut sp[..l] {
            *v *= gs;
        }
        let mut fin = [0f32; 54];
        filt(&sp[..l], &mut self.out_hist, &mut fin[..l]);
        out.extend(fin[..l].iter().map(|&v| (v / 32768.0).clamp(-1.0, 1.0)));
    }
}

/// An EVRC decoder: one per stream, fed packets in order.
#[derive(Clone)]
pub struct Decoder {
    lsp_prev: [f32; 10],
    tau_prev: f32,
    /// Adaptive codebook memory E(-128..0).
    exc: [f32; MEM],
    /// The last valid frame's memory.
    elv: [f32; MEM],
    gp_avg: f32,
    /// gpavg of the last valid frame.
    gp_avg_valid: f32,
    gc_avg: f32,
    fade: f32,
    fer_prev: bool,
    last_valid: Dr,
    fgidx_prev: usize,
    noise: Noise,
    syn: [f32; 10],
    pf: Postfilter,
    postfilter: bool,
}

impl Default for Decoder {
    fn default() -> Self {
        Self::new()
    }
}

impl Decoder {
    pub fn new() -> Self {
        Decoder {
            lsp_prev: lsp_spread(),
            tau_prev: 40.0,
            exc: [0.0; MEM],
            elv: [0.0; MEM],
            gp_avg: 0.0,
            gp_avg_valid: 0.0,
            gc_avg: 0.0,
            fade: 1.0,
            fer_prev: false,
            last_valid: Dr::Eighth,
            fgidx_prev: 0,
            noise: Noise {
                rng: Rng { seed: 0 },
                spare: None,
            },
            syn: [0.0; 10],
            pf: Postfilter::new(),
            postfilter: true,
        }
    }

    /// Back to the start-up state (a seek); the postfilter choice is kept.
    pub fn reset(&mut self) {
        let pf = self.postfilter;
        *self = Self::new();
        self.postfilter = pf;
    }

    /// Turns the adaptive postfilter (§5.4, optional per §1.1) on or off; on by default.
    pub fn set_postfilter(&mut self, on: bool) {
        self.postfilter = on;
    }

    /// Decodes one stored packet (rate byte and payload, or a bare payload of 22, 10 or 2
    /// bytes) and appends [`FRAME_SAMPLES`] samples in -1..1. Anything unreadable decodes
    /// as an erased frame.
    pub fn decode(&mut self, packet: &[u8], out: &mut Vec<f32>) {
        let (rate, payload) = split(packet);
        self.decode_frame(rate, payload, out);
    }

    /// Decodes one frame of a known rate (`payload` without the rate byte).
    pub fn decode_frame(&mut self, rate: Rate, payload: &[u8], out: &mut Vec<f32>) {
        let start = out.len();
        let recv = match rate {
            Rate::Full if payload.len() >= 22 => Some(Dr::Full),
            Rate::Half if payload.len() >= 10 => Some(Dr::Half),
            Rate::Eighth if payload.len() >= 2 => Some(Dr::Eighth),
            _ => None,
        };
        // §5.1.1 received packet type processing
        let mut fer = recv.is_none();
        if recv == Some(Dr::Eighth) && payload[0] == 0xff && payload[1] == 0xff {
            fer = true; // null traffic data
        }
        let mut drate = recv.unwrap_or(Dr::Full);
        if fer {
            drate = if self.last_valid == Dr::Eighth {
                Dr::Eighth
            } else {
                Dr::Full
            };
        }
        if drate == Dr::Eighth && self.last_valid == Dr::Full && !self.fer_prev {
            fer = true;
            drate = Dr::Full;
        }
        if !fer {
            self.last_valid = drate;
        }
        let f = if fer {
            Frame::default()
        } else {
            parse(drate, payload)
        };
        match drate {
            Dr::Eighth => self.eighth(fer, &f, out),
            _ => self.voiced(fer, drate, &f, out),
        }
        out.truncate(start + FRAME_SAMPLES);
        out.resize(start + FRAME_SAMPLES, 0.0);
    }

    fn eighth(&mut self, mut fer: bool, f: &Frame, out: &mut Vec<f32>) {
        let mut lsp = self.lsp_prev;
        if !fer {
            match decode_lsp(Dr::Eighth, &f.lsp) {
                Some(w) => lsp = w,
                None => fer = true,
            }
        }
        let gains: [f32; 3] = if fer {
            let row = QLOG[self.fgidx_prev];
            let m = row.iter().map(|&q| 10f32.powf(q)).sum::<f32>() / 3.0;
            [m; 3]
        } else {
            self.fgidx_prev = f.fgidx;
            QLOG[f.fgidx].map(|q| 10f32.powf(q))
        };
        for (sf, &l) in SUB.iter().enumerate() {
            let a = self.interp_lpc(&lsp, sf);
            let mut ex = [0f32; 54];
            for v in &mut ex[..l] {
                *v = gains[sf] * self.noise.next();
            }
            // The noise also feeds the adaptive codebook memory (§5.3 names no state here,
            // but FFmpeg's decoder does this, and the following rate 1 and 1/2 frames only
            // match it this way).
            self.exc.copy_within(l.., 0);
            self.exc[MEM - l..].copy_from_slice(&ex[..l]);
            let s = self.synth(&ex[..l], &a);
            self.post(&s[..l], &a, Dr::Eighth, None, out);
        }
        self.lsp_prev = lsp;
        self.fer_prev = fer;
    }

    fn voiced(&mut self, mut fer: bool, rate: Dr, f: &Frame, out: &mut Vec<f32>) {
        // §5.1.2 / §5.1.3 delay checks
        if !fer && f.delay > 100 {
            fer = true;
        }
        let tau_now = f.delay as f32 + 20.0;
        let tau_rec = tau_now - f.ddelay as f32 + 16.0;
        if !fer
            && rate == Dr::Full
            // DDELAY 0 says the delay jumped by more than 15 (4.5.3-2): nothing to check
            && f.ddelay != 0
            && !(20.0..=120.0).contains(&tau_rec)
        {
            fer = true;
        }
        // §5.2.1 LSPs
        let lsp = if fer { None } else { decode_lsp(rate, &f.lsp) };
        if lsp.is_none() {
            fer = true;
        }
        let lsp = lsp.unwrap_or_else(|| {
            let sp = lsp_spread();
            std::array::from_fn(|k| 0.875 * self.lsp_prev[k] + 0.125 * sp[k])
        });
        // §5.2.2.1 delay
        let tau = if fer { self.tau_prev } else { tau_now };
        let mut tau_prev = self.tau_prev;
        // §5.2.2.2 delay contour reconstruction after an erasure
        if !fer && self.fer_prev && rate == Dr::Full {
            self.exc = self.elv;
            let mut tp = self.tau_prev;
            if (tau_rec - tp).abs() > 15.0 {
                tp = tau_rec;
            }
            for (sf, &l) in SUB.iter().enumerate() {
                let d: [f32; 3] = std::array::from_fn(|j| {
                    let fj = FD[sf + j];
                    (1.0 - fj) * tp + fj * tau_rec
                });
                let mut buf = [0f32; MEM + 64];
                buf[..MEM].copy_from_slice(&self.exc);
                acb(&mut buf, &d, l);
                self.exc.copy_within(l.., 0);
                self.exc[MEM - l..].copy_from_slice(&buf[MEM..MEM + l]);
            }
            tau_prev = tau_rec;
        }
        // §5.2.2.3 smoothing
        if (tau - tau_prev).abs() > 15.0 {
            tau_prev = tau;
        }
        // §5.2.3.5 average adaptive codebook gain on erasures
        if fer && self.fer_prev {
            self.gp_avg *= 0.75;
        }
        let gc_cb: &[f32] = if rate == Dr::Full { &GC_FULL } else { &GC_HALF };
        let mut gps = [0f32; 3];
        let mut gcs = [0f32; 3];
        for (sf, &l) in SUB.iter().enumerate() {
            let mut a = self.interp_lpc(&lsp, sf);
            if rate == Dr::Full && f.lpcflag && self.fer_prev {
                let mut p = 1f32;
                for c in &mut a {
                    p *= 0.75;
                    *c *= p;
                }
            }
            // §5.2.3.4 interpolated delays
            let d: [f32; 3] = if fer && self.gp_avg_valid < 0.3 {
                std::array::from_fn(|j| D_RND[sf + j])
            } else if (tau - tau_prev).abs() > 15.0 {
                [tau; 3]
            } else {
                std::array::from_fn(|j| {
                    let fj = FD[sf + j];
                    (1.0 - fj) * tau_prev + fj * tau
                })
            };
            let sub = &f.sub[sf];
            let gp = if fer {
                self.gp_avg
            } else {
                GP_CB[sub.acbg & 7]
            };
            let gc = if fer {
                self.gc_avg
            } else {
                gc_cb[sub.fcbg.min(gc_cb.len() - 1)]
            };
            gps[sf] = gp;
            gcs[sf] = gc;
            // adaptive codebook
            let mut buf = [0f32; MEM + 64];
            buf[..MEM].copy_from_slice(&self.exc);
            acb(&mut buf, &d, l);
            // fixed codebook
            let mut c = [0f32; 55];
            if !fer {
                match rate {
                    Dr::Full => acelp_full(&sub.fcbs, &mut c),
                    _ => acelp_half(sub.fcbs[0], &mut c),
                }
                let t = ((d[0] + d[1]) / 2.0).round() as usize;
                if t < 55 {
                    let g = gp.clamp(0.2, 0.9);
                    for j in t..55 {
                        c[j] += g * c[j - t];
                    }
                }
            }
            let mut et = [0f32; 54];
            for n in 0..l {
                et[n] = gp * buf[MEM + n] + if fer { 0.0 } else { gc * c[n] };
            }
            // §5.2.3.9 memory update
            self.exc.copy_within(l.., 0);
            self.exc[MEM - l..].copy_from_slice(&et[..l]);
            if !fer && sf == 2 {
                self.elv = self.exc;
            }
            // §5.2.3.10 fade and random excitation
            self.fade = if fer {
                self.fade - 0.05
            } else {
                self.fade + 0.2
            }
            .clamp(0.0, 1.0);
            for v in &mut et[..l] {
                *v *= self.fade;
            }
            if fer && self.gp_avg < 0.4 {
                let g = 0.1 * self.gc_avg;
                for v in &mut et[..l] {
                    *v += g * self.noise.next();
                }
            }
            let s = self.synth(&et[..l], &a);
            let dl = (d[0] + d[1]) / 2.0;
            self.post(&s[..l], &a, rate, Some(dl), out);
        }
        if !fer {
            self.gp_avg = gps.iter().sum::<f32>() / 3.0;
            self.gp_avg_valid = self.gp_avg;
            self.gc_avg = gcs.iter().sum::<f32>() / 3.0;
        }
        self.tau_prev = tau;
        self.lsp_prev = lsp;
        self.fer_prev = fer;
    }

    /// The postfilter, or the plain synthesis when it is off; scaled to -1..1.
    fn post(&mut self, s: &[f32], a: &[f32; 10], rate: Dr, delay: Option<f32>, out: &mut Vec<f32>) {
        if self.postfilter {
            self.pf.run(s, a, rate, delay, out);
        } else {
            out.extend(s.iter().map(|&v| (v / 32768.0).clamp(-1.0, 1.0)));
        }
    }

    fn interp_lpc(&self, lsp: &[f32; 10], sf: usize) -> [f32; 10] {
        let mu = MU[sf];
        let w: [f32; 10] = std::array::from_fn(|k| (1.0 - mu) * self.lsp_prev[k] + mu * lsp[k]);
        lsp_to_lpc(&w)
    }

    /// The synthesis filter 1 / A(z) (5.2.3.11-1).
    fn synth(&mut self, ex: &[f32], a: &[f32; 10]) -> [f32; 54] {
        let mut s = [0f32; 54];
        for n in 0..ex.len() {
            let mut v = ex[n];
            for k in 0..10 {
                v += a[k] * self.syn[9 - k];
            }
            if !v.is_finite() {
                v = 0.0;
            }
            v = v.clamp(-1.0e6, 1.0e6);
            self.syn.copy_within(1.., 0);
            self.syn[9] = v;
            s[n] = v;
        }
        s
    }
}

/// The adaptive codebook contribution mapped to the delay contour (§4.5.5): `buf` holds
/// E(-128..0) at `..MEM`; E(0..L+10) is written after it.
fn acb(buf: &mut [f32; MEM + 64], d: &[f32; 3], l: usize) {
    const FL: i64 = 8;
    const R: f32 = 8.0;
    for n in 0..l + 10 {
        let tc = if n < l {
            d[0] + n as f32 * (d[1] - d[0]) / l as f32
        } else {
            d[1] + (n - l) as f32 * (d[2] - d[1]) / l as f32
        };
        let mut te = if tc > 0.0 {
            tc.round() as i64
        } else {
            -((-tc).round() as i64)
        };
        let mut tie = ((te as f32 - tc + 0.5) * R + 0.5) as i64;
        if tie == 8 {
            tie = 0;
            te -= 1;
        }
        let tie = tie.clamp(0, 7) as usize;
        let mut v = 0f32;
        for i in 0..=2 * FL {
            let at = MEM as i64 + i + n as i64 - te - FL;
            if (0..(MEM + n) as i64).contains(&at) {
                v += buf[at as usize] * IE[i as usize + 17 * tie];
            }
        }
        buf[MEM + n] = v;
    }
}

fn sign(bit: u32) -> f32 {
    if bit == 0 { 1.0 } else { -1.0 }
}

fn pulse(c: &mut [f32; 55], track: usize, lambda: u32, s: f32) {
    let p = 5 * lambda as usize + track;
    if p < 55 {
        c[p] += s;
    }
}

/// The rate 1 algebraic codebook (§4.5.7.1, §4.5.7.3, §5.2.3.7).
fn acelp_full(idx: &[u32; 4], c: &mut [f32; 55]) {
    let q = (idx[3] >> 9) as usize & 3;
    for i in 0..3 {
        let track = (q + i) % 5;
        let v = idx[i] & 127;
        let s = sign((idx[i] >> 7) & 1);
        let (l0, l1) = (v / 11, v % 11);
        if l0 <= l1 {
            pulse(c, track, l0, s);
            pulse(c, track, l1, s);
        } else {
            pulse(c, track, l0, s);
            pulse(c, track, l1, -s);
        }
    }
    let v = idx[3] & 127;
    pulse(c, (q + 3) % 5, v / 11, sign((idx[3] >> 8) & 1));
    pulse(c, (q + 4) % 5, v % 11, sign((idx[3] >> 7) & 1));
}

/// The rate 1/2 algebraic codebook (§4.5.7.4).
fn acelp_half(idx: u32, c: &mut [f32; 55]) {
    let s = sign((idx >> 9) & 1);
    let q = [(idx >> 6) & 7, (idx >> 3) & 7, idx & 7];
    for (t, &qt) in q.iter().enumerate() {
        let p = 7 * qt as usize + 2 * t;
        c[p] += if t == 1 { -s } else { s };
    }
}

/// Splits a stored packet into its rate and payload.
fn split(p: &[u8]) -> (Rate, &[u8]) {
    if let Some(&b) = p.first()
        && let (Some(r), Some(n)) = (Rate::from_byte(b), packet_len(b))
        && p.len() >= n
    {
        // a bare payload of the same length as a whole packet of another rate wins only
        // when the rate byte does not fit
        if p.len() == n || Rate::from_len(p.len()).is_none() {
            return (r, &p[1..n]);
        }
    }
    match Rate::from_len(p.len()) {
        Some(r) => (r, p),
        None => (Rate::Erasure, &[]),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn packet_lengths() {
        assert_eq!(packet_len(4), Some(23));
        assert_eq!(packet_len(3), Some(11));
        assert_eq!(packet_len(1), Some(3));
        assert_eq!(packet_len(0), Some(1));
        assert_eq!(packet_len(14), Some(1));
        assert_eq!(packet_len(9), None);
        for r in [Rate::Full, Rate::Half, Rate::Eighth] {
            assert_eq!(Rate::from_len(r.payload_bytes()), Some(r));
        }
    }

    #[test]
    fn lpc_of_spread_lsps_is_stable() {
        let a = lsp_to_lpc(&lsp_spread());
        // the impulse response of 1/A(z) decays
        let mut mem = [0f32; 10];
        let mut last = 0f32;
        for n in 0..2000 {
            let mut v = if n == 0 { 1.0 } else { 0.0 };
            for k in 0..10 {
                v += a[k] * mem[9 - k];
            }
            mem.copy_within(1.., 0);
            mem[9] = v;
            last = v;
        }
        assert!(last.abs() < 1e-3, "{last}");
    }

    #[test]
    fn garbage_never_panics() {
        let mut d = Decoder::new();
        let mut out = Vec::new();
        let mut x = 0x1234_5678u32;
        for i in 0..3000usize {
            let len = i % 30;
            let p: Vec<u8> = (0..len)
                .map(|_| {
                    x ^= x << 13;
                    x ^= x >> 17;
                    x ^= x << 5;
                    x as u8
                })
                .collect();
            d.decode(&p, &mut out);
            assert_eq!(out.len(), (i + 1) * FRAME_SAMPLES);
        }
        assert!(out.iter().all(|v| v.is_finite() && v.abs() <= 1.0));
    }
}
