//! Specular's own Theora video decoder (Theora I specification, bitstream 3.2.x), for Ogg
//! and Matroska playback.
//!
//! Decodes intra and inter frames in all three pixel formats (4:2:0, 4:2:2, 4:4:4): every
//! macro block mode including four motion vectors and the golden frame, block-level qi
//! values, DC prediction, the bit-exact inverse DCT and the loop filter. Pictures are cropped
//! to the picture region and returned top row first (Theora stores frames bottom-up). A
//! zero-length packet repeats the previous frame.
//!
//! VP3.1, Theora's headerless predecessor (AVI `VP31`), decodes through
//! [`Decoder::new_vp3`] with VP3's built-in tables from the specification's Appendix B
//! (`src/vp3_setup.rs`, generated by `tools/corpus/specular-theora-vp3-setup.py`) and VP3's
//! own frame header, run lengths and four-vector macro blocks.
//!
//! Frames of any size the headers can give (up to 1,048,560 pixels on a side) decode when the
//! memory budget holds their buffers.
//!
//! Refused: the pre-release Theora alpha bitstreams (3.0, 3.1: no specification describes
//! them and no sample was found) and VP3.0 (`VP30`: no sample found).
//!
//! Output is bit-exact with libtheora and ffmpeg. A damaged frame returns an error and
//! leaves the reference frames as they were.
#![deny(unsafe_code)]
// Block loops index several per-block tables at once, in the specification's terms.
#![allow(clippy::needless_range_loop)]

mod bits;
mod decode;
mod layout;
mod recon;
