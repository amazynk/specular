mod vp3_setup;

/// Why a stream or frame can't be decoded.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Error {
    /// A valid stream using something this decoder doesn't do.
    Unsupported(String),
    /// The bitstream is damaged or breaks the format.
    Malformed(String),
    /// A valid stream whose buffers the memory budget cannot hold now.
    NeedsMemory(specular_core::NeedsMemory),
}

impl std::fmt::Display for Error {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Error::Unsupported(s) => write!(f, "unsupported: {s}"),
            Error::Malformed(s) => write!(f, "damaged Theora video: {s}"),
            Error::NeedsMemory(n) => write!(f, "this video {n}"),
        }
    }
}

impl std::error::Error for Error {}

pub(crate) fn malformed(s: &str) -> Error {
    Error::Malformed(s.into())
}

/// Chroma subsampling of the Cb and Cr planes.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Chroma {
    /// Half width, half height.
    C420,
    /// Half width, full height.
    C422,
    /// Full size.
    C444,
}

/// The identification header.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Info {
    /// Coded frame size (multiples of 16).
    pub frame_width: u32,
    pub frame_height: u32,
    /// The picture region shown.
    pub pic_width: u32,
    pub pic_height: u32,
    /// Offset of the picture region from the left edge.
    pub pic_x: u32,
    /// Offset of the picture region from the bottom edge (as stored).
    pub pic_y: u32,
    /// Frames per second as numerator, denominator.
    pub fps: (u32, u32),
    /// Pixel aspect ratio; (0, 0) when unknown.
    pub aspect: (u32, u32),
    /// 0 undefined, 1 Rec. 470M, 2 Rec. 470BG.
    pub colour_space: u8,
    pub chroma: Chroma,
    /// Granule position split: key frame number above this many bits.
    pub keyframe_granule_shift: u8,
    /// Bitstream version (major, minor, revision); (3, 1, 0) for headerless VP3.1 frames.
    pub version: (u8, u8, u8),
    /// Headerless VP3.1 frames ([`Decoder::new_vp3`]): VP3's frame header, run lengths and
    /// four-vector macro blocks, with the setup data of the specification's Appendix B.
    pub vp3: bool,
}

impl Info {
    /// Parses the identification header packet (0x80 "theora").
    pub fn parse(ident: &[u8]) -> Result<Info, Error> {
        if ident.len() < 7 || ident[0] != 0x80 || &ident[1..7] != b"theora" {
            return Err(malformed("not a Theora identification header"));
        }
        if ident.len() < 42 {
            return Err(malformed("identification header is cut short"));
        }
        let mut br = bits::Bits::new(&ident[7..]);
        let version = (br.read(8) as u8, br.read(8) as u8, br.read(8) as u8);
        if version.0 != 3 || version.1 != 2 {
            return Err(Error::Unsupported(format!(
                "Theora {}.{} video",
                version.0, version.1
            )));
        }
        let fmbw = br.read(16);
        let fmbh = br.read(16);
        let pic_width = br.read(24);
        let pic_height = br.read(24);
        let pic_x = br.read(8);
        let pic_y = br.read(8);
        let fps = (br.read(32), br.read(32));
        let aspect = (br.read(24), br.read(24));
        let colour_space = br.read(8) as u8;
        let _nominal_bitrate = br.read(24);
        let _quality = br.read(6);
        let keyframe_granule_shift = br.read(5) as u8;
        let chroma = match br.read(2) {
            0 => Chroma::C420,
            2 => Chroma::C422,
            3 => Chroma::C444,
            _ => return Err(malformed("reserved pixel format")),
        };
        if br.read(3) != 0 {
            return Err(malformed("reserved bits set in the identification header"));
        }
        let (frame_width, frame_height) = (fmbw * 16, fmbh * 16);
        if fmbw == 0 || fmbh == 0 || pic_width == 0 || pic_height == 0 {
            return Err(malformed("empty frame size"));
        }
        if pic_x + pic_width > frame_width || pic_y + pic_height > frame_height {
            return Err(malformed("picture region outside the frame"));
        }
        Ok(Info {
            frame_width,
            frame_height,
            pic_width,
            pic_height,
            pic_x,
            pic_y,
            fps,
            aspect,
            colour_space,
            chroma,
            keyframe_granule_shift,
            version,
            vp3: false,
        })
    }
}

/// A decoded frame.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Picture {
    /// Size of the picture region.
    pub width: u32,
    pub height: u32,
    pub chroma: Chroma,
    /// Y, Cb, Cr, top row first, cropped to the picture region; chroma planes are ceil-sized
    /// (e.g. 4:2:0: (width + 1) / 2 × (height + 1) / 2), rows tightly packed.
    pub planes: [Vec<u8>; 3],
    pub keyframe: bool,
}

/// A Theora decoder for one stream.
pub struct Decoder {
    state: decode::State,
}

impl Decoder {
    /// From the identification and setup header packets (comment header not needed).
    pub fn new(ident: &[u8], setup: &[u8]) -> Result<Decoder, Error> {
        let info = Info::parse(ident)?;
        let setup = setup::parse(setup)?;
        Ok(Decoder {
            state: decode::State::new(info, setup)?,
        })
    }

    /// For VP3.1 frames (AVI `VP31`, Matroska `V_VP3`...), which carry no headers: the
    /// frame size comes from the container; VP3's tables are built in (Theora specification,
    /// Appendix B). The frame is the size rounded up to whole macro blocks, the picture its
    /// top-left `width` × `height`. VP3 is 4:2:0 only and names no colour space.
    pub fn new_vp3(width: u32, height: u32) -> Result<Decoder, Error> {
        if width == 0 || height == 0 {
            return Err(malformed("empty frame size"));
        }
        // Theora's largest frame (16-bit macro block counts); the memory budget decides the
        // rest.
        if width > 0xFFFF0 || height > 0xFFFF0 {
            return Err(Error::Unsupported(format!("{width}×{height} VP3 video")));
        }
        let (frame_width, frame_height) = (width.div_ceil(16) * 16, height.div_ceil(16) * 16);
        let info = Info {
            frame_width,
            frame_height,
            pic_width: width,
            pic_height: height,
            pic_x: 0,
            pic_y: frame_height - height,
            fps: (0, 0),
            aspect: (0, 0),
            colour_space: 0,
            chroma: Chroma::C420,
            keyframe_granule_shift: 0,
            version: (3, 1, 0),
            vp3: true,
        };
        let setup = setup::parse(&vp3_setup::VP3_SETUP)?;
        Ok(Decoder {
            state: decode::State::new(info, setup)?,
        })
    }

    pub fn info(&self) -> &Info {
        &self.state.info
    }

    /// Decodes one frame packet. A zero-length packet repeats the previous frame (returns it again).
    /// Inter frames before the first keyframe: Err(Malformed) (caller skips).
    pub fn decode(&mut self, packet: &[u8]) -> Result<Picture, Error> {
        self.state.decode(packet)
    }

    /// Forgets the reference frames (after a seek); the next frame must be a keyframe.
    pub fn reset(&mut self) {
        self.state.reset();
    }
}

/// Whether a frame packet is a keyframe (first bit 0, then frame type bit 0).
pub fn is_keyframe(packet: &[u8]) -> bool {
    packet.first().is_some_and(|&b| b & 0xc0 == 0)
}

/// Whether a VP3.1 frame is a key frame (first bit 0).
pub fn is_vp3_keyframe(packet: &[u8]) -> bool {
    packet.first().is_some_and(|&b| b & 0x80 == 0)
}

/// Splits Matroska's CodecPrivate (Xiph lacing of the three headers).
pub fn split_xiph_laced(private: &[u8]) -> Option<[&[u8]; 3]> {
    let (&count, mut rest) = private.split_first()?;
    if count != 2 {
        return None;
    }
    let mut sizes = [0usize; 2];
    for s in sizes.iter_mut() {
        loop {
            let (&b, r) = rest.split_first()?;
            rest = r;
            *s += usize::from(b);
            if b != 255 {
                break;
            }
        }
    }
    if sizes[0] + sizes[1] > rest.len() {
        return None;
    }
    let (a, rest) = rest.split_at(sizes[0]);
    let (b, c) = rest.split_at(sizes[1]);
    Some([a, b, c])
}
