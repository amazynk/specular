"""Writes src/epsg_axes.rs: the EPSG projected CRSs whose first axis points north or south
(northing before easting), from PROJ's database through pyproj. GML and WFS data that
name their CRS by URN or http URI follow the EPSG axis order, so their coordinates are
swapped for these codes and for every geographic CRS (latitude first).

Usage: python -I epsg_axes.py OUT.rs
"""

import sys

from pyproj import CRS
from pyproj.database import query_crs_info
from pyproj.enums import PJType


def main():
    codes = []
    for info in query_crs_info(auth_name="EPSG", pj_types=[PJType.PROJECTED_CRS]):
        try:
            axes = CRS.from_epsg(int(info.code)).axis_info
        except Exception:  # noqa: BLE001 - codes PROJ cannot build
            continue
        if axes and axes[0].direction.lower() in ("north", "south"):
            codes.append(int(info.code))
    codes.sort()
    with open(sys.argv[1], "w") as out:
        out.write("//! EPSG projected CRSs whose first axis is northing (generated by gen/epsg_axes.py\n")
        out.write("//! from PROJ's database; do not edit).\n\n")
        out.write(f"/// {len(codes)} codes, sorted.\n")
        out.write("pub const NORTH_FIRST: &[u32] = &[\n")
        for i in range(0, len(codes), 10):
            out.write("    " + ", ".join(str(c) for c in codes[i : i + 10]) + ",\n")
        out.write("];\n\n")
        out.write("/// Whether projected EPSG CRS `code` lists northing before easting.\n")
        out.write("pub fn north_first(code: u32) -> bool {\n    NORTH_FIRST.binary_search(&code).is_ok()\n}\n")
    print(f"{len(codes)} north-first projected CRSs")


if __name__ == "__main__":
    main()
