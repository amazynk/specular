"""Writes src/s57_catalogue.rs: the S-57 object classes and attributes by code, with their
acronyms, names and attribute types. The codes are the IHO S-57 Edition 3.1 object
catalogue's (Appendix A, with the Inland ENC and AML additions); they are read from the
catalogue files GDAL ships as data (s57objectclasses.csv and s57attributes.csv, MIT), for
example those inside the pyogrio wheel:

    python -I s57_catalogue.py .../pyogrio/gdal_data ../src/s57_catalogue.rs
"""

import csv
import os
import sys


def rows(path):
    with open(path, newline="", encoding="latin-1") as f:
        r = csv.reader(f)
        next(r)
        for row in r:
            if not row or not row[0].strip().lstrip("-").isdigit():
                continue
            yield row


def rust(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    data, out = sys.argv[1], sys.argv[2]
    objects = {}
    for row in rows(os.path.join(data, "s57objectclasses.csv")):
        code = int(row[0])
        if 0 < code < 65536 and code not in objects:
            objects[code] = (row[2].strip(), row[1].strip())
    attrs = {}
    for row in rows(os.path.join(data, "s57attributes.csv")):
        code = int(row[0])
        if 0 < code < 65536 and code not in attrs:
            kind = row[3].strip() or "S"
            attrs[code] = (row[2].strip(), row[1].strip(), kind[0])
    with open(out, "w", encoding="utf-8") as o:
        o.write(
            "//! The S-57 object catalogue's codes (IHO S-57 Edition 3.1 Appendix A, with the\n"
            "//! Inland ENC and AML additions): generated by gen/s57_catalogue.py from the catalogue\n"
            "//! files GDAL ships as data (MIT); do not edit.\n\n"
        )
        o.write("/// Object classes: (code, acronym, name), sorted by code.\n")
        o.write(f"pub const OBJECTS: &[(u16, &str, &str)] = &[\n")
        for code in sorted(objects):
            a, n = objects[code]
            o.write(f"    ({code}, {rust(a)}, {rust(n)}),\n")
        o.write("];\n\n")
        o.write(
            "/// Attributes: (code, acronym, name, type), sorted by code. Types: `E` enumerated,\n"
            "/// `L` list of enumerated, `F` float, `I` integer, `A` coded string, `S` free text.\n"
        )
        o.write("pub const ATTRIBUTES: &[(u16, &str, &str, u8)] = &[\n")
        for code in sorted(attrs):
            a, n, k = attrs[code]
            o.write(f"    ({code}, {rust(a)}, {rust(n)}, b'{k}'),\n")
        o.write("];\n")


main()
