"""Writes tests/data/labels_oracle.tsv: segment volumes of the corpus SEG and RTSTRUCT files, the
oracle for tests/labels.rs.

Needs highdicom and pydicom (test oracles only, never dependencies of Specular), e.g. in a venv
under target/:

    python3 -m venv target/venv && target/venv/bin/pip install pydicom==3.0.1 highdicom==0.28.2
    target/venv/bin/python -I gen/labels_oracle.py CORPUS > tests/data/labels_oracle.tsv

SEG: highdicom decodes each segmentation into a volume (Segmentation.get_volume); per segment
the voxels above 0, the summed fractions (1 per binary voxel) and the volume, mL (summed
fractions × the volume's voxel size). Files highdicom cannot decode (RLE of 1-bit data,
deflate, big endian) are left out.

RTSTRUCT: pydicom reads the CLOSED_PLANAR contours (all axial here); per ROI the sum over its
planes of the contour areas (shoelace; a contour inside an odd number of others on its plane is
a hole) times the median distance between its planes (the set's median when it has one plane).

Lines: kind, file (relative to CORPUS), segment number, voxels (SEG; - for RTSTRUCT), mL.
"""
import glob
import os
import sys

import highdicom as hd
import numpy as np
import pydicom

SEGS = [
    "highdicom/data/test_files/seg_image_ct_*.dcm",
    "dcmqi/data/segmentations/*.dcm",
    "pydicom-data/data_store/data/liver*.dcm",
    "pydicom/src/pydicom/data/test_files/liver_1frame.dcm",
]
RTSS = [
    "pydicom/src/pydicom/data/test_files/rtstruct.dcm",
    "tcia-sts/rtss-pt/*.dcm",
    "tcia-sts/rtss-ct/*.dcm",
]


def seg_rows(root, rel):
    try:
        s = hd.seg.segread(os.path.join(root, rel))
        v = s.get_volume(combine_segments=False, skip_overlap_checks=True)
    except Exception as e:  # noqa: BLE001 - files highdicom cannot decode are skipped
        print(f"# skipped {rel}: {type(e).__name__}", file=sys.stderr)
        return
    a = np.asarray(v.array, dtype=np.float64)
    voxel_ml = float(np.prod(v.spacing)) / 1000.0
    numbers = [int(x) for x in s.segment_numbers]
    for i, n in enumerate(numbers):
        m = a[..., i]
        yield ("SEG", rel, n, int((m > 0).sum()), float(m.sum()) * voxel_ml)


def inside(poly, q):
    c = False
    n = len(poly)
    for i in range(n):
        a, b = poly[i], poly[(i + 1) % n]
        if (a[1] > q[1]) != (b[1] > q[1]):
            x = a[0] + (q[1] - a[1]) * (b[0] - a[0]) / (b[1] - a[1])
            if q[0] < x:
                c = not c
    return c


def area(poly):
    x = np.array([p[0] for p in poly])
    y = np.array([p[1] for p in poly])
    return abs(float(np.dot(x, np.roll(y, -1)) - np.dot(np.roll(x, -1), y))) / 2.0


def rt_rows(root, rel):
    d = pydicom.dcmread(os.path.join(root, rel), force=True)
    rois = {}
    for rc in d.ROIContourSequence:
        planes = {}
        for c in rc.get("ContourSequence", []):
            pts = [float(x) for x in c.ContourData]
            if c.ContourGeometricType != "CLOSED_PLANAR" or len(pts) < 9:
                continue
            p = [pts[i : i + 3] for i in range(0, len(pts), 3)]
            z = round(sum(q[2] for q in p) / len(p), 3)
            planes.setdefault(z, []).append([(q[0], q[1]) for q in p])
        rois[int(rc.ReferencedROINumber)] = planes
    every = sorted({z for planes in rois.values() for z in planes})
    gaps = [b - a for a, b in zip(every, every[1:]) if b - a > 0.05]
    fallback = sorted(gaps)[len(gaps) // 2] if gaps else 1.0
    for n, planes in rois.items():
        zs = sorted(planes)
        g = sorted(b - a for a, b in zip(zs, zs[1:]) if b - a > 0.05)
        step = g[len(g) // 2] if g else fallback
        total = 0.0
        for polys in planes.values():
            for i, p in enumerate(polys):
                depth = sum(1 for j, o in enumerate(polys) if j != i and inside(o, p[0]))
                total += -area(p) if depth % 2 else area(p)
        yield ("RTSTRUCT", rel, n, "-", total * step / 1000.0)


def main():
    root = sys.argv[1]
    print(f"# @generated by gen/labels_oracle.py (highdicom {hd.__version__}, pydicom {pydicom.__version__}). Do not edit.")
    rows = []
    for pat in SEGS:
        for f in sorted(glob.glob(os.path.join(root, pat))):
            rows.extend(seg_rows(root, os.path.relpath(f, root)))
    for pat in RTSS:
        for f in sorted(glob.glob(os.path.join(root, pat))):
            rows.extend(rt_rows(root, os.path.relpath(f, root)))
    for r in rows:
        print("\t".join(str(x) if not isinstance(x, float) else f"{x:.9g}" for x in r))


if __name__ == "__main__":
    main()
