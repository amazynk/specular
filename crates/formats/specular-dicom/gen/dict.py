"""Generates src/dict_table.rs, the compact data-element dictionary.

Source: the DICOM PS3.6 data dictionary in pydicom's machine-readable copy (pydicom is used
here as a data source only, never at run time). Run with a Python that has pydicom installed:

    python -I gen/dict.py src/dict_table.rs

Kept: the groups an image viewer reads or may show (file meta, identification, patient (for
the tag browser's names only: values are never shown by default), acquisition, relationship,
image presentation, frame-of-reference, procedure, presentation states, nuclear medicine, icon,
presentation LUT, pixel data, segmentation, ophthalmology, waveforms, RT dose, plans and
structure sets, DICONDE (0014)). Repeating-group entries (`xx` in the tag) are skipped.
Ambiguous VRs take the first choice, except LUT data ("US or OW", "US or SS or OW") which is
OW.
"""
import sys

from pydicom._dicom_dict import DicomDictionary

GROUPS = {0x0002, 0x0008, 0x0010, 0x0014, 0x0018, 0x0020, 0x0022, 0x0028, 0x0032, 0x0038,
          0x003A, 0x0040, 0x0054, 0x0062, 0x0070, 0x0088, 0x2050, 0x3004, 0x3006, 0x300A,
          0x300C, 0x5200, 0x5400, 0x7FE0}
VRS = {"AE", "AS", "AT", "CS", "DA", "DS", "DT", "FD", "FL", "IS", "LO", "LT", "OB", "OD",
       "OF", "OL", "OV", "OW", "PN", "SH", "SL", "SQ", "SS", "ST", "SV", "TM", "UC", "UI",
       "UL", "UN", "UR", "US", "UT", "UV"}


def vr_of(v):
    if v in VRS:
        return v
    if "OW" in v and "US" in v:
        return "OW"
    first = v.split(" or ")[0]
    return first if first in VRS else "UN"


def main(out):
    rows = []
    for tag, (vr, _vm, _name, _retired, keyword) in sorted(DicomDictionary.items()):
        if (tag >> 16) not in GROUPS or not keyword:
            continue
        rows.append("    (0x%08X, %s, %s)," % (tag, vr_of(vr), '"%s"' % keyword))
    with open(out, "w", encoding="utf-8") as f:
        f.write("// @generated by gen/dict.py from the DICOM PS3.6 data dictionary. Do not edit.\n")
        f.write("// %d entries, sorted by tag.\n\n" % len(rows))
        f.write("use crate::dict::Vr::{self, *};\n\n")
        f.write("#[rustfmt::skip]\n")
        f.write("pub(crate) static ENTRIES: &[(u32, Vr, &str)] = &[\n")
        f.write("\n".join(rows))
        f.write("\n];\n")


if __name__ == "__main__":
    main(sys.argv[1])
