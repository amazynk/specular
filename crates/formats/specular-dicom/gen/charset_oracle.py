"""Writes tests/data/charset_oracle.tsv: pydicom's decoding of every text value in pydicom's
character set test files (tools/corpus/fetch-dicom.sh src_pydicom_charset), the oracle for
tests/charset.rs.

Needs pydicom (a test oracle only, never a dependency of Specular), e.g. in a venv under
target/:

    python3 -m venv target/venv && target/venv/bin/pip install pydicom==3.0.1
    target/venv/bin/python -I gen/charset_oracle.py CORPUS/pydicom/src/pydicom/data/charset_files

Standard (not private) elements only. Lines: file, element path (tags as GGGGEEEE, items as [n]), value with \\ \t \n \r escaped.
Values are normalised as in tests/charset.rs: each value (split on '\\' except for LT, ST, UT)
stripped of spaces and NULs, and PN values of trailing '^' and '='. The files hold the standard's example names, no patient data.
"""
import os
import sys

import pydicom
from pydicom.charset import decode_element

VRS = {"SH", "LO", "ST", "LT", "UC", "UT", "PN"}
SINGLE = {"LT", "ST", "UT"}


def norm(text, vr):
    parts = [text] if vr in SINGLE else text.split("\\")
    parts = [p.strip(" \0") for p in parts]
    if vr == "PN":
        # Trailing empty components and groups ("Wang^XiaoDong=王^小東=").
        parts = [p.rstrip("^=") for p in parts]
    return "\\".join(parts)


def esc(s):
    return s.replace("\\", "\\\\").replace("\t", "\\t").replace("\n", "\\n").replace("\r", "\\r")


def walk(ds, prefix, encodings, out):
    if "SpecificCharacterSet" in ds:
        encodings = ds.SpecificCharacterSet
    for elem in ds:
        path = prefix + "%08X" % elem.tag
        if elem.VR == "SQ":
            for i, item in enumerate(elem.value):
                walk(item, path + "[%d]/" % i, encodings, out)
            continue
        if elem.VR not in VRS or elem.value is None or elem.tag.is_private:
            continue
        raw = elem.value
        if isinstance(raw, (bytes, bytearray)):
            decode_element(elem, encodings)
        value = elem.value
        if elem.VM > 1 or isinstance(value, (list, pydicom.multival.MultiValue)):
            text = "\\".join(str(v) for v in value)
        else:
            text = str(value)
        out.append((path, norm(text, elem.VR)))


def main(folder, dest):
    rows = []
    for name in sorted(os.listdir(folder)):
        if not name.endswith(".dcm"):
            continue
        ds = pydicom.dcmread(os.path.join(folder, name))
        out = []
        walk(ds, "", ds.get("SpecificCharacterSet", ""), out)
        rows += [(name, p, v) for p, v in out]
    with open(dest, "w", encoding="utf-8", newline="\n") as f:
        f.write("# @generated by gen/charset_oracle.py (pydicom %s). Do not edit.\n"
                % pydicom.__version__)
        for name, p, v in rows:
            f.write("%s\t%s\t%s\n" % (name, p, esc(v)))


if __name__ == "__main__":
    here = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    main(sys.argv[1], os.path.join(here, "tests", "data", "charset_oracle.tsv"))
