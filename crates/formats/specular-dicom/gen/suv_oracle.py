"""Writes tests/data/suv_oracle.tsv: SUV factors and SUVmax of the corpus PET series (TCIA
Soft-tissue-Sarcoma STS_010, tools/corpus/fetch-dicom.sh src_tcia_sts), the oracle for
tests/suv.rs.

Needs pydicom and numpy (test oracles only, never dependencies of Specular), e.g. in a venv
under target/:

    target/venv/bin/python -I gen/suv_oracle.py CORPUS > tests/data/suv_oracle.tsv

pydicom reads the tags and pixels; the SUV arithmetic is written out here on its own from the
QIBA vendor-neutral pseudo-code (BQML, decay correction START: the dose decayed from the
injection to the series time; the injection's date-time when it gives a delay within a day,
else its time on the series' date) with James' lean body mass and Du Bois' surface area.

Lines: file (relative to CORPUS) or "series", SUVbw factor, SUVlbm factor, SUVbsa factor,
delay (s), then for "series" the SUVbw max over all slices and the voxel it is at
(file, column, row).
"""
import datetime as dt
import glob
import math
import os
import sys

import numpy as np
import pydicom


def when(date, time):
    time = time.replace(":", "")
    whole, _, frac = time.partition(".")
    whole = whole.ljust(6, "0")
    t = dt.datetime.strptime(date + whole, "%Y%m%d%H%M%S")
    return t + dt.timedelta(seconds=float("0." + frac) if frac else 0.0)


def factors(d):
    rp = d.RadiopharmaceuticalInformationSequence[0]
    scan = when(d.SeriesDate, d.SeriesTime)
    acq = when(d.AcquisitionDate, d.AcquisitionTime)
    assert scan <= acq, "series after acquisition: not the case in this corpus"
    inj = None
    if "RadiopharmaceuticalStartDateTime" in rp:
        v = str(rp.RadiopharmaceuticalStartDateTime)
        inj = when(v[:8], v[8:].split("+")[0].split("-")[0])
        if not (0 <= (scan - inj).total_seconds() < 86400):
            inj = None
    if inj is None:
        inj = when(d.SeriesDate, str(rp.RadiopharmaceuticalStartTime))
        if inj > scan:
            inj -= dt.timedelta(days=1)
    delay = (scan - inj).total_seconds()
    assert d.Units == "BQML" and d.DecayCorrection == "START"
    decay = math.exp(-delay * math.log(2) / float(rp.RadionuclideHalfLife))
    w = float(d.PatientWeight)
    h = float(d.PatientSize) * 100.0
    dose = float(rp.RadionuclideTotalDose) * decay
    bw = w * 1000.0 / dose
    lbm = (1.10 * w - 128 * (w / h) ** 2) if d.PatientSex == "M" else (1.07 * w - 148 * (w / h) ** 2)
    bsa = 0.007184 * w**0.425 * h**0.725
    return bw, lbm * 1000.0 / dose, bsa * 10000.0 / dose, delay


def main():
    root = sys.argv[1]
    files = sorted(glob.glob(os.path.join(root, "tcia-sts/pt/*.dcm")))
    print(f"# @generated by gen/suv_oracle.py (pydicom {pydicom.__version__}). Do not edit.")
    best = (-1.0, None, 0, 0)
    for i, f in enumerate(files):
        d = pydicom.dcmread(f)
        bw, lbm, bsa, delay = factors(d)
        rel = os.path.relpath(f, root)
        if i in (0, len(files) // 2, len(files) - 1):
            print(f"{rel}\t{bw:.12g}\t{lbm:.12g}\t{bsa:.12g}\t{delay:.6g}")
        a = d.pixel_array.astype(np.float64) * float(d.RescaleSlope) + float(d.RescaleIntercept)
        j = int(np.argmax(a))
        if a.flat[j] * bw > best[0]:
            best = (a.flat[j] * bw, rel, j % a.shape[1], j // a.shape[1])
    print(f"series\t{best[0]:.12g}\t{best[1]}\t{best[2]}\t{best[3]}")


if __name__ == "__main__":
    main()
