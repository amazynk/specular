"""Generates src/deid_table.rs, the de-identification action table.

Source: DICOM PS3.15 Table E.1-1 "Application Level Confidentiality Profile Attributes", read
from the standard's DocBook XML (https://dicom.nema.org/medical/dicom/current/source/docbook/
part15/part15.xml). VRs come from pydicom's machine-readable copy of the PS3.6 dictionary
(pydicom is used here as a data source only, never at run time). Run with a Python that has
pydicom installed:

    python -I gen/deid.py path/to/part15.xml src/deid_table.rs

Every row of the table becomes one entry: the tag, a mask for repeating groups (`xx` in the
tag, e.g. (50xx,xxxx)), the VR, the Basic Profile action exactly as the standard writes it
(compound codes such as X/Z/D are kept; the de-identifier resolves them) and, per option
column, whether the option keeps (K) or cleans (C) the attribute. The "private attributes"
row is skipped: private groups are matched by parity, not by tag, and are always removed.
"""
import re
import sys
import xml.etree.ElementTree as ET

from pydicom._dicom_dict import DicomDictionary, RepeatersDictionary

NS = {"d": "http://docbook.org/ns/docbook"}
# Option columns, in table order after "Basic Prof.". The bit index is the position here.
OPTIONS = ["RtnSafePriv", "RtnUIDs", "RtnDevId", "RtnInstId", "RtnPatChars",
           "RtnLongFullDates", "RtnLongModifDates", "CleanDesc", "CleanStructCont",
           "CleanGraph"]
BASIC = {"D": "D", "Z": "Z", "X": "X", "K": "K", "C": "C", "U": "U", "X/Z": "XZ",
         "X/D": "XD", "Z/D": "ZD", "X/Z/D": "XZD", "X/Z/U*": "XZU"}
VRS = {"AE", "AS", "AT", "CS", "DA", "DS", "DT", "FD", "FL", "IS", "LO", "LT", "OB", "OD",
       "OF", "OL", "OV", "OW", "PN", "SH", "SL", "SQ", "SS", "ST", "SV", "TM", "UC", "UI",
       "UL", "UN", "UR", "US", "UT", "UV"}


def text(td):
    return " ".join("".join(td.itertext()).split())


def vr_of(v):
    if v in VRS:
        return v
    if "OW" in v and "US" in v:
        return "OW"
    first = v.split(" or ")[0]
    return first if first in VRS else "UN"


def lookup_vr(tag_text, tag, mask):
    if mask == 0xFFFFFFFF:
        entry = DicomDictionary.get(tag)
        return vr_of(entry[0]) if entry else "UN"
    key = tag_text.replace("(", "").replace(")", "").replace(",", "").upper().replace("X", "x")
    entry = RepeatersDictionary.get(key)
    return vr_of(entry[0]) if entry else "UN"


def parse_tag(s):
    m = re.fullmatch(r"\(([0-9A-Fa-fx]{4}),([0-9A-Fa-fx]{4})\)", s)
    if not m:
        return None
    hexs = m.group(1) + m.group(2)
    tag = 0
    mask = 0
    for c in hexs:
        tag <<= 4
        mask <<= 4
        if c in "xX":
            continue
        tag |= int(c, 16)
        mask |= 0xF
    return tag, mask


def main(xml, out):
    root = ET.parse(xml)
    table = [t for t in root.iter("{%s}table" % NS["d"]) if t.get("label") == "E.1-1"][0]
    head = [text(th) for th in table.find("d:thead", NS).iter("{%s}th" % NS["d"])]
    rows = []
    skipped = []
    for tr in table.find("d:tbody", NS).findall("d:tr", NS):
        cells = [text(td) for td in tr.findall("d:td", NS)]
        if len(cells) != 15:
            raise SystemExit("unexpected row width %d: %r" % (len(cells), cells))
        name, tag_text, basic = cells[0].replace("\u200b", ""), cells[1], cells[4]
        parsed = parse_tag(tag_text)
        if parsed is None:
            skipped.append(tag_text + " " + name)
            continue
        tag, mask = parsed
        if basic not in BASIC:
            raise SystemExit("unknown basic action %r for %s" % (basic, tag_text))
        keep = clean = 0
        for i, cell in enumerate(cells[5:15]):
            if cell == "K":
                keep |= 1 << i
            elif cell == "C":
                clean |= 1 << i
            elif cell:
                raise SystemExit("unknown option code %r for %s" % (cell, tag_text))
        vr = lookup_vr(tag_text, tag, mask)
        rows.append((tag, mask, vr, BASIC[basic], keep, clean, name))
    rows.sort()
    with open(out, "w", encoding="utf-8") as f:
        f.write("// @generated by gen/deid.py from DICOM PS3.15 Table E.1-1. Do not edit.\n")
        f.write("// %d entries, sorted by tag. Columns: tag, mask (repeating groups), VR, Basic\n"
                % len(rows))
        f.write("// Profile action, option bits that keep (K), option bits that clean (C).\n")
        f.write("// Option bit order: %s.\n" % ", ".join(OPTIONS))
        f.write("// Skipped rows: %s.\n\n" % "; ".join(skipped))
        f.write("use crate::anon::Basic::{self, *};\n")
        f.write("use crate::dict::Vr;\n\n")
        f.write("#[rustfmt::skip]\n")
        f.write("pub(crate) static ENTRIES: &[(u32, u32, Vr, Basic, u16, u16)] = &[\n")
        for tag, mask, vr, basic, keep, clean, name in rows:
            f.write("    (0x%08X, 0x%08X, Vr::%s, %s, 0x%03X, 0x%03X), // %s\n"
                    % (tag, mask, vr, basic, keep, clean, name))
        f.write("];\n")
    if head[:2] != ["Attribute Name", "Tag"]:
        print("warning: unexpected header %r" % head[:2], file=sys.stderr)


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
