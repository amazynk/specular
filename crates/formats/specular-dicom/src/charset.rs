//! Text decoding by Specific Character Set (0008,0005), PS3.5 §6.1.
//!
//! - Single-byte sets: ISO_IR 100/101/109/110/144/127/126/138/148/203/166 (ISO 8859 parts and
//!   TIS 620) and ISO_IR 13 (JIS X 0201).
//! - ISO 2022 code extensions: ISO 2022 IR 6, the single-byte sets above, IR 13, IR 87 (JIS X
//!   0208), IR 159 (JIS X 0212), IR 149 (KS X 1001) and IR 58 (GB 2312). Escape sequences switch
//!   G0 / G1; the state returns to that of value 1 before value delimiters ('\'), before the PN
//!   delimiters '^' and '=', and before control characters (CR, LF, FF, TAB, ...).
//! - Without code extensions: ISO_IR 192 (UTF-8), GB18030 and GBK.
//!
//! Tables are generated by gen/charset.py from the Unicode consortium's and WHATWG's mapping
//! files. Lenient with real-world spellings ("ISO_IR100", "ISO-IR 100", "UTF-8", "GB2312") and
//! data: unknown terms decode as ISO_IR 100, as do high bytes with no G1 designated; undecodable
//! bytes become U+FFFD.

use crate::charset_table::{GB18030_RANGES, SINGLE_BYTE};
use crate::dict::Vr;
use crate::parse::{DataSet, Values};

static JIS0208: &[u8] = include_bytes!("charset_data/jis0208.bin");
static JIS0212: &[u8] = include_bytes!("charset_data/jis0212.bin");
static KSX1001: &[u8] = include_bytes!("charset_data/ksx1001.bin");
static GB18030: &[u8] = include_bytes!("charset_data/gb18030.bin");

/// Specific Character Set (0008,0005).
pub const SPECIFIC_CHARACTER_SET: u32 = 0x0008_0005;

/// A single-byte set's upper half, in the order of `SINGLE_BYTE`.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum SingleByte {
    Latin1,
    Latin2,
    Latin3,
    Latin4,
    Cyrillic,
    Arabic,
    Greek,
    Hebrew,
    Latin5,
    Latin9,
    Thai,
}

/// A graphic set that can be designated to G0 (bytes 0x21..=0x7E).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum G0 {
    /// ISO 646 IRV (ASCII); JIS X 0201 Romaji is decoded the same, as DICOM keeps 0x5C the
    /// value delimiter.
    Ascii,
    Jis0208,
    Jis0212,
}

/// A graphic set that can be designated to G1 (bytes 0xA0..=0xFF).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum G1 {
    Single(SingleByte),
    /// JIS X 0201 Katakana.
    Katakana,
    Ksx1001,
    Gb2312,
}

/// One defined term of Specific Character Set.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Term {
    Ascii,
    Single(SingleByte),
    Jis0201,
    Jis0208,
    Jis0212,
    Ksx1001,
    Gb2312,
    Utf8,
    Gb18030,
    Gbk,
    Unknown,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Kind {
    Iso2022 {
        g0: G0,
        g1: Option<G1>,
        /// Used for high bytes while no G1 set is designated.
        fallback: G1,
    },
    Utf8,
    /// GB18030 (also GBK, a subset of it).
    Gb18030,
}

/// How a data set's text values are encoded.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Charset {
    kind: Kind,
}

impl Default for Charset {
    /// No Specific Character Set: ASCII, with ISO_IR 100 for high bytes (common in old files).
    fn default() -> Charset {
        Charset {
            kind: Kind::Iso2022 {
                g0: G0::Ascii,
                g1: None,
                fallback: G1::Single(SingleByte::Latin1),
            },
        }
    }
}

fn term(raw: &[u8]) -> Term {
    let t: Vec<u8> = raw
        .iter()
        .filter(|b| !matches!(b, b' ' | b'_' | b'-'))
        .map(u8::to_ascii_uppercase)
        .collect();
    let t = t.as_slice();
    if t.is_empty() {
        return Term::Ascii;
    }
    match t {
        b"UTF8" | b"ISOIR192" => return Term::Utf8,
        b"GB18030" => return Term::Gb18030,
        b"GBK" | b"GB2312" | b"EUCCN" => return Term::Gbk,
        _ => {}
    }
    let number = t
        .strip_prefix(b"ISO2022IR")
        .or_else(|| t.strip_prefix(b"ISOIR"));
    let Some(n) = number.and_then(|n| std::str::from_utf8(n).ok()?.parse::<u16>().ok()) else {
        return Term::Unknown;
    };
    use SingleByte::*;
    match n {
        6 => Term::Ascii,
        100 => Term::Single(Latin1),
        101 => Term::Single(Latin2),
        109 => Term::Single(Latin3),
        110 => Term::Single(Latin4),
        144 => Term::Single(Cyrillic),
        127 => Term::Single(Arabic),
        126 => Term::Single(Greek),
        138 => Term::Single(Hebrew),
        148 => Term::Single(Latin5),
        203 => Term::Single(Latin9),
        166 => Term::Single(Thai),
        13 => Term::Jis0201,
        87 => Term::Jis0208,
        159 => Term::Jis0212,
        149 => Term::Ksx1001,
        58 => Term::Gb2312,
        _ => Term::Unknown,
    }
}

fn g1_of(t: Term) -> Option<G1> {
    match t {
        Term::Single(s) => Some(G1::Single(s)),
        Term::Jis0201 => Some(G1::Katakana),
        Term::Ksx1001 => Some(G1::Ksx1001),
        Term::Gb2312 => Some(G1::Gb2312),
        _ => None,
    }
}

impl Charset {
    /// From the raw value of Specific Character Set (backslash-separated defined terms).
    pub fn parse(value: &[u8]) -> Charset {
        let terms: Vec<Term> = value
            .split(|&b| b == b'\\')
            .map(|t| term(t.trim_ascii()))
            .collect();
        let first = terms[0];
        let iso2022_multi = terms.iter().any(|t| {
            matches!(
                t,
                Term::Jis0208 | Term::Jis0212 | Term::Ksx1001 | Term::Gb2312
            )
        });
        // Without code extensions; also tolerated when misplaced after an empty value 1.
        for t in &terms {
            if !iso2022_multi || *t == first {
                match t {
                    Term::Utf8 => return Charset { kind: Kind::Utf8 },
                    Term::Gb18030 | Term::Gbk => {
                        return Charset {
                            kind: Kind::Gb18030,
                        };
                    }
                    _ => {}
                }
            }
        }
        let g1 = g1_of(first);
        let fallback = g1
            .or_else(|| terms.iter().skip(1).find_map(|t| g1_of(*t)))
            .unwrap_or(G1::Single(SingleByte::Latin1));
        Charset {
            kind: Kind::Iso2022 {
                g0: G0::Ascii,
                g1,
                fallback,
            },
        }
    }

    /// The character set of `ds` (default when it has none).
    pub fn of(ds: &DataSet, v: &Values) -> Charset {
        ds.get(SPECIFIC_CHARACTER_SET)
            .map(|e| Charset::parse(v.text_bytes(e)))
            .unwrap_or_default()
    }

    /// The character set of a sequence item: its own Specific Character Set, else `self`
    /// (the enclosing data set's).
    pub fn within(self, item: &DataSet, v: &Values) -> Charset {
        item.get(SPECIFIC_CHARACTER_SET)
            .map(|e| Charset::parse(v.text_bytes(e)))
            .unwrap_or(self)
    }

    /// Decodes a text value of representation `vr` (which decides the delimiters at which ISO
    /// 2022 code extensions return to the initial state).
    pub fn decode(&self, bytes: &[u8], vr: Vr) -> String {
        if bytes.is_ascii() && !bytes.contains(&0x1B) {
            return bytes.iter().map(|&b| b as char).collect();
        }
        match self.kind {
            Kind::Utf8 => String::from_utf8_lossy(bytes).into_owned(),
            Kind::Gb18030 => gb18030(bytes),
            Kind::Iso2022 { g0, g1, fallback } => iso2022(bytes, vr, g0, g1, fallback),
        }
    }
}

fn cell(table: &[u8], i: usize) -> Option<char> {
    let c = u16::from_le_bytes([*table.get(2 * i)?, *table.get(2 * i + 1)?]);
    (c != 0).then(|| char::from_u32(c.into())).flatten()
}

/// A 94 x 94 set's character for bytes `a`, `b` (both 0x21..=0x7E, or both 0xA1..=0xFE).
fn square(table: &[u8], a: u8, b: u8) -> char {
    let (a, b) = ((a & 0x7F) as usize, (b & 0x7F) as usize);
    if !(0x21..=0x7E).contains(&a) || !(0x21..=0x7E).contains(&b) {
        return '\u{FFFD}';
    }
    cell(table, (a - 0x21) * 94 + (b - 0x21)).unwrap_or('\u{FFFD}')
}

/// The designation of an escape sequence (after ESC) and its length.
fn escape(rest: &[u8]) -> Option<(usize, Result<G0, G1>)> {
    use SingleByte::*;
    Some(match rest {
        [b'(', b'B' | b'J', ..] => (2, Ok(G0::Ascii)),
        [b'$', b'B' | b'@', ..] => (2, Ok(G0::Jis0208)),
        [b'$', b'(', b'D', ..] => (3, Ok(G0::Jis0212)),
        [b')', b'I', ..] => (2, Err(G1::Katakana)),
        [b'$', b')', b'C', ..] => (3, Err(G1::Ksx1001)),
        [b'$', b')', b'A', ..] => (3, Err(G1::Gb2312)),
        [b'-', f, ..] => {
            let s = match f {
                b'A' => Latin1,
                b'B' => Latin2,
                b'C' => Latin3,
                b'D' => Latin4,
                b'L' => Cyrillic,
                b'G' => Arabic,
                b'F' => Greek,
                b'H' => Hebrew,
                b'M' => Latin5,
                b'b' => Latin9,
                b'T' => Thai,
                _ => return None,
            };
            (2, Err(G1::Single(s)))
        }
        _ => return None,
    })
}

fn iso2022(bytes: &[u8], vr: Vr, init_g0: G0, init_g1: Option<G1>, fallback: G1) -> String {
    let pn = vr == Vr::PN;
    // Single-valued text VRs may contain '\' as a character.
    let multi = !matches!(vr, Vr::LT | Vr::ST | Vr::UT | Vr::UR);
    let delimiter = |b: u8| {
        (b < 0x20 && b != 0x1B) || (multi && b == b'\\') || (pn && (b == b'^' || b == b'='))
    };
    let (mut g0, mut g1) = (init_g0, init_g1);
    let mut out = String::with_capacity(bytes.len());
    let mut i = 0;
    while i < bytes.len() {
        let b = bytes[i];
        if b == 0x1B {
            match escape(&bytes[i + 1..]) {
                Some((n, d)) => {
                    match d {
                        Ok(s) => g0 = s,
                        Err(s) => g1 = Some(s),
                    }
                    i += 1 + n;
                }
                None => {
                    out.push('\u{FFFD}');
                    i += 1;
                }
            }
            continue;
        }
        if b < 0x80 {
            let wide = match g0 {
                G0::Ascii => None,
                G0::Jis0208 => Some(JIS0208),
                G0::Jis0212 => Some(JIS0212),
            };
            match wide {
                Some(t) if (0x21..0x7F).contains(&b) => {
                    match bytes.get(i + 1) {
                        Some(&c) if (0x21..0x7F).contains(&c) => out.push(square(t, b, c)),
                        _ => out.push('\u{FFFD}'),
                    }
                    i += 2;
                }
                _ => {
                    if delimiter(b) {
                        (g0, g1) = (init_g0, init_g1);
                    }
                    out.push(b as char);
                    i += 1;
                }
            }
            continue;
        }
        match g1.unwrap_or(fallback) {
            G1::Single(s) => {
                out.push(if b < 0xA0 {
                    b as char
                } else {
                    let c = SINGLE_BYTE[s as usize][(b - 0xA0) as usize];
                    char::from_u32(c.into()).unwrap_or('\u{FFFD}')
                });
                i += 1;
            }
            G1::Katakana => {
                out.push(match b {
                    0xA1..=0xDF => {
                        char::from_u32(0xFF61 + u32::from(b - 0xA1)).unwrap_or('\u{FFFD}')
                    }
                    _ => '\u{FFFD}',
                });
                i += 1;
            }
            set @ (G1::Ksx1001 | G1::Gb2312) => {
                match bytes.get(i + 1) {
                    Some(&c) if (0xA1..=0xFE).contains(&c) && b >= 0xA1 => {
                        // GB 2312 is the 0xA1..=0xFE square of GB18030's two-byte table.
                        out.push(if set == G1::Ksx1001 {
                            square(KSX1001, b, c)
                        } else {
                            gb_two(b, c)
                        });
                        i += 2;
                    }
                    _ => {
                        out.push('\u{FFFD}');
                        i += 1;
                    }
                }
            }
        }
    }
    out
}

/// GB18030's two-byte character for lead `a` (0x81..=0xFE) and trail `b`.
fn gb_two(a: u8, b: u8) -> char {
    let trail = match b {
        0x40..=0x7E => b - 0x40,
        0x80..=0xFE => b - 0x41,
        _ => return '\u{FFFD}',
    };
    cell(GB18030, (a as usize - 0x81) * 190 + trail as usize).unwrap_or('\u{FFFD}')
}

/// GB18030's character for a four-byte pointer.
fn gb_four(p: u32) -> char {
    if (39420..189_000).contains(&p) || p > 1_237_575 {
        return '\u{FFFD}';
    }
    if p == 7457 {
        return '\u{E7C7}';
    }
    let at = GB18030_RANGES.partition_point(|r| r.0 <= p);
    let Some(&(start, cp)) = at.checked_sub(1).and_then(|i| GB18030_RANGES.get(i)) else {
        return '\u{FFFD}';
    };
    char::from_u32(cp + p - start).unwrap_or('\u{FFFD}')
}

fn gb18030(bytes: &[u8]) -> String {
    let mut out = String::with_capacity(bytes.len());
    let mut i = 0;
    while i < bytes.len() {
        let b = bytes[i];
        if b < 0x80 {
            out.push(b as char);
            i += 1;
            continue;
        }
        if b == 0x80 || b == 0xFF {
            out.push(if b == 0x80 { '\u{20AC}' } else { '\u{FFFD}' });
            i += 1;
            continue;
        }
        let digit = |x: Option<&u8>| {
            x.filter(|x| x.is_ascii_digit())
                .map(|x| u32::from(x - b'0'))
        };
        let lead = |x: Option<&u8>| {
            x.filter(|x| (0x81..=0xFE).contains(*x))
                .map(|x| u32::from(x - 0x81))
        };
        if let Some(d2) = digit(bytes.get(i + 1)) {
            match (lead(bytes.get(i + 2)), digit(bytes.get(i + 3))) {
                (Some(b3), Some(d4)) => {
                    let p = ((u32::from(b - 0x81) * 10 + d2) * 126 + b3) * 10 + d4;
                    out.push(gb_four(p));
                    i += 4;
                }
                _ => {
                    out.push('\u{FFFD}');
                    i += 1;
                }
            }
            continue;
        }
        match bytes.get(i + 1) {
            Some(&c) if c >= 0x40 && c != 0x7F && c != 0xFF => {
                out.push(gb_two(b, c));
                i += 2;
            }
            _ => {
                out.push('\u{FFFD}');
                i += 1;
            }
        }
    }
    out
}

