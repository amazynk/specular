/// The DC scaler of a block (Table 7-1) for luma (`luma`) or chroma at quantiser `qp`.
pub(crate) fn dc_scaler(qp: i32, luma: bool) -> i32 {
    let q = qp.clamp(1, 31);
    if luma {
        match q {
            1..=4 => 8,
            5..=8 => 2 * q,
            9..=24 => q + 8,
            _ => 2 * q - 16,
        }
    } else {
        match q {
            1..=4 => 8,
            5..=24 => (q + 13) / 2,
            _ => q - 6,
        }
    }
}
