//! Inputs found by the fuzzer (`fuzz/`), minimised, checked against the invariant they broke.

use specular_jpeg::*;

/// The fuzz target's indexed region decode: every parallelism gives the same result.
fn indexed_region_decodes_agree(data: &[u8]) {
    let info = read_info(data).unwrap();
    let region = Region {
        x: info.width / 3,
        y: info.height / 4,
        w: info.width / 2 + 1,
        h: info.height / 3 + 1,
    };
    let o = DecodeOptions {
        scale: Scale::Half,
        region: Some(region),
        ..Default::default()
    };
    let ix = build_index(data).unwrap();
    let first = decode_with_index(data, &ix, &o);
    for parallelism in [
        Parallelism::Single,
        Parallelism::Threads(2),
        Parallelism::Threads(3),
    ] {
        let o = DecodeOptions { parallelism, ..o };
        match (&first, &decode_with_index(data, &ix, &o)) {
            (Ok(a), Ok(b)) => assert!(a == b, "{parallelism:?}: indexed decode differs"),
            (a, b) => assert_eq!(a.is_ok(), b.is_ok(), "{parallelism:?}: outcome"),
        }
    }
}

