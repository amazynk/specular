/// The group delay for firmware version `dspfvs` and decimation `decim`, when the table has
/// it.
pub fn group_delay(dspfvs: i64, decim: f64) -> Option<f64> {
    TABLE
        .iter()
        .find(|(v, d, _)| i64::from(*v) == dspfvs && f64::from(*d) == decim)
        .map(|t| t.2)
}

#[cfg(test)]
mod tests {
    #[test]
    fn known_values() {
        assert_eq!(super::group_delay(10, 4.0), Some(66.625));
        assert_eq!(super::group_delay(13, 2.0), Some(2.75));
        assert_eq!(super::group_delay(20, 4.0), None);
    }
}
